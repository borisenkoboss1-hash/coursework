function инициализироватьПоискНаГлавной() {
    const поле = document.getElementById('поле-поиска');
    const кнопка = document.getElementById('кнопка-поиска');
    if (!поле) return;

    function перейтиВКаталог() {
        const запрос = поле.value.trim();
        if (запрос) {
            window.location.href = `catalog.html?search=${encodeURIComponent(запрос)}`;
        }
    }

    кнопка && кнопка.addEventListener('click', перейтиВКаталог);
    поле.addEventListener('keypress', e => {
        if (e.key === 'Enter') перейтиВКаталог();
    });
}

