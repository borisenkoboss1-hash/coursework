/**
 * Инициализация строки поиска на главной странице
 * При нажатии на кнопку или Enter:
 * - Берёт текст из поля ввода
 * - Если текст не пустой — перенаправляет на catalog.html с параметром search
 * Далее каталог сам разберёт этот параметр и покажет отфильтрованные товары
 */
function инициализироватьПоискНаГлавной() {
    const поле = document.getElementById('поле-поиска');
    const кнопка = document.getElementById('кнопка-поиска');
    if (!поле) return; // на главной странице поле есть, но проверка не помешает

    function перейтиВКаталог() {
        const запрос = поле.value.trim();
        if (запрос) {
            // Передаём поисковую строку через URL-параметр search
            window.location.href = `catalog.html?search=${encodeURIComponent(запрос)}`;
        }
    }

    // Клик по кнопке "Найти"
    кнопка && кнопка.addEventListener('click', перейтиВКаталог);
    // Нажатие Enter в поле ввода
    поле.addEventListener('keypress', e => {
        if (e.key === 'Enter') перейтиВКаталог();
    });
}

