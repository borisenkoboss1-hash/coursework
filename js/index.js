/**
 * Инициализация переключателей (табов) для секций "Межкомнатные" и "Входные"
 * Логика:
 * - Находит все группы табов (класс .секция-табы) — у нас их две (для межкомнатных и входных)
 * - Для каждой кнопки вешает обработчик клика
 * - При клике:
 *   1) Убирает active у всех кнопок в этой группе
 *   2) Добавляет active нажатой
 *   3) Определяет, какой контейнер сетки находится внутри той же секции (по id: сетка-межком или сетка-входные)
 *   4) В зависимости от порядка кнопки (0,1,2) выбирает режим: 'popular', 'new', 'sale'
 *   5) Перерисовывает секцию с новым режимом
 */
function инициализироватьТабы() {
    document.querySelectorAll('.секция-табы').forEach(группаТабов => {
        const кнопки = группаТабов.querySelectorAll('.секция-таб');
        кнопки.forEach((кнопка, индекс) => {
            кнопка.addEventListener('click', () => {
                // Снимаем active со всех кнопок этой группы
                кнопки.forEach(к => к.classList.remove('active'));
                кнопка.classList.add('active');

                // Находим родительскую секцию (с классом .контейнер, который оборачивает и табы, и сетку)
                const секция = группаТабов.closest('.контейнер');
                // Внутри этой секции находим сетку товаров
                const сетка = секция.querySelector('.сетка-главная');
                if (!сетка) return;

                // Определяем категорию по ID сетки
                const категория = сетка.id === 'сетка-межком' ? 'interior' : 'entrance';
                // Маппинг позиции кнопки в режим фильтрации
                const режимы = ['popular', 'new', 'sale'];
                // Перерисовываем
                нарисоватьСекцию(сетка.id, категория, режимы[индекс]);
            });
        });
    });
}

