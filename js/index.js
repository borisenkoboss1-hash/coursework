/**
 * Функция создания слайдера на странице
 * Срабатывает при загрузке DOM
 * 
 * Логика: 
 * 1. Находит контейнеры по ID
 * 2. Создаёт трек (внутренний контейнер с overflow hidden, который двигается)
 * 3. Для каждого слайда из данныеСлайдов добавляет HTML в трек и точку-индикатор
 * 4. Вешает обработчики на кнопки "влево/вправо"
 * 5. Запускает автопрокрутку каждые 4 секунды
 */
function создатьСлайдер() {
    const слайдер = document.getElementById('слайдер');
    const точки = document.getElementById('слайдер-точки');

    // Трек — это длинная горизонтальная полоса, где все слайды расположены в ряд
    const трек = document.createElement('div');
    трек.className = 'слайдер-трек';
    трек.id = 'слайдер-трек';

    // Проходим по всем данным и строим HTML для каждого слайда
    данныеСлайдов.forEach((с, i) => {
        трек.innerHTML += `
            <div class="слайд ${с.класс}">
                <div class="слайд-контент">
                    <h2>${с.заголовок}</h2>
                    <p>${с.описание}</p>
                    <div class="слайд-цена">${с.цена}</div>
                    <a href="${с.ссылка}" class="слайд-кнопка">Подробнее →</a>
                </div>
                <div class="слайд-картинка">
                    ${с.картинка ? `<img src="${с.картинка}" alt="Дверь" style="max-width:100%; border-radius:12px; max-height:300px; object-fit:cover;">` : с.иконка}
                    <div class="слайд-скидка">${с.скидка}</div>
                </div>
            </div>`;

        // Создаём точку-индикатор (кружочек внизу слайдера)
        const точка = document.createElement('button');
        точка.className = 'точка' + (i === 0 ? ' active' : '');
        // При клике на точку — переходим на соответствующий слайд
        точка.addEventListener('click', () => перейтиНаСлайд(i));
        точки.appendChild(точка);
    });

    // Добавляем трек в слайдер
    слайдер.appendChild(трек);

    // Обработчики для стрелок
    document.getElementById('слайд-влево').addEventListener('click', () => {
        // Формула прокрутки назад с зацикливанием (если 0, то переходит на последний)
        const новый = (текущийСлайд - 1 + данныеСлайдов.length) % данныеСлайдов.length;
        перейтиНаСлайд(новый);
    });
    document.getElementById('слайд-вправо').addEventListener('click', () => {
        const новый = (текущийСлайд + 1) % данныеСлайдов.length;
        перейтиНаСлайд(новый);
    });

    // Запускаем автоматическую смену слайдов
    таймерСлайдера = setInterval(() => {
        перейтиНаСлайд((текущийСлайд + 1) % данныеСлайдов.length);
    }, 4000);
}

/**
 * Переход на слайд с указанным индексом
 * @param {number} индекс - индекс слайда (0-based)
 * 
 * Что делает:
 * - Обновляет текущий слайд
 * - Сдвигает трек с помощью transform: translateX()
 * - Обновляет активные точки
 * - Сбрасывает и перезапускает автопрокрутку (чтобы не сбивался тайминг)
 */
function перейтиНаСлайд(индекс) {
    текущийСлайд = индекс;
    const трек = document.getElementById('слайдер-трек');
    // Сдвигаем трек влево на ширину одного слайда (100% от родителя)
    if (трек) трек.style.transform = `translateX(-${индекс * 100}%)`;

    // Обновляем активный класс у точек
    document.querySelectorAll('.точка').forEach((т, i) => {
        т.classList.toggle('active', i === индекс);
    });

    // Сбрасываем старый таймер и запускаем новый — важный нюанс:
    // если пользователь сам кликнул, автопрокрутка начинается заново, а не накапливается
    clearInterval(таймерСлайдера);
    таймерСлайдера = setInterval(() => {
        перейтиНаСлайд((текущийСлайд + 1) % данныеСлайдов.length);
    }, 4000);
}

