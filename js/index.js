// ==================== СЛАЙДЕР ====================

let текущийСлайд = 0;
let таймерСлайдера;

function создатьСлайдер() {
    const слайдер = document.getElementById('слайдер');
    const точки = document.getElementById('слайдер-точки');

    // Создаём трек со всеми слайдами
    const трек = document.createElement('div');
    трек.className = 'слайдер-трек';
    трек.id = 'слайдер-трек';

    данныеСлайдов.forEach((с, i) => {
        трек.innerHTML += `
            <div class="слайд ${с.класс}">
                <div class="слайд-контент">
                    <h2>${с.заголовок}</h2>
                    <p>${с.описание}</p>
                    <div class="слайд-цена">${с.цена}</div>
                    <a href="${с.ссылка}" class="слайд-кнопка">Подробнее →</a>
                </div>
               <div class="слайд-картинка">
    ${с.картинка ? `<img src="${с.картинка}" alt="Дверь" style="max-width:100%; border-radius:12px; max-height:300px; object-fit:cover;">` : с.иконка}
    <div class="слайд-скидка">${с.скидка}</div>
</div>
            </div>`;

        // Добавляем точку
        const точка = document.createElement('button');
        точка.className = 'точка' + (i === 0 ? ' active' : '');
        точка.addEventListener('click', () => перейтиНаСлайд(i));
        точки.appendChild(точка);
    });

    слайдер.appendChild(трек);

    // Кнопки стрелок
    document.getElementById('слайд-влево').addEventListener('click', () => {
        const новый = (текущийСлайд - 1 + данныеСлайдов.length) % данныеСлайдов.length;
        перейтиНаСлайд(новый);
    });
    document.getElementById('слайд-вправо').addEventListener('click', () => {
        const новый = (текущийСлайд + 1) % данныеСлайдов.length;
        перейтиНаСлайд(новый);
    });

    // Автопрокрутка каждые 4 секунды
    таймерСлайдера = setInterval(() => {
        перейтиНаСлайд((текущийСлайд + 1) % данныеСлайдов.length);
    }, 4000);
}

function перейтиНаСлайд(индекс) {
    текущийСлайд = индекс;
    const трек = document.getElementById('слайдер-трек');
    if (трек) трек.style.transform = `translateX(-${индекс * 100}%)`;

    // Обновляем точки
    document.querySelectorAll('.точка').forEach((т, i) => {
        т.classList.toggle('active', i === индекс);
    });

    // Сбрасываем таймер при ручном переключении
    clearInterval(таймерСлайдера);
    таймерСлайдера = setInterval(() => {
        перейтиНаСлайд((текущийСлайд + 1) % данныеСлайдов.length);
    }, 4000);
}

// ==================== ЗАГРУЗКА ТОВАРОВ ====================

async function загрузитьТовары() {
    try {
        const resp = await fetch('data/products.json');
        всеТовары = await resp.json();
        нарисоватьСекцию('сетка-межком', 'interior', 'popular');
        нарисоватьСекцию('сетка-входные', 'entrance', 'popular');
        нарисоватьОтзывы();
    } catch (e) {
        console.error('Ошибка загрузки товаров:', e);
    }
}

// ==================== СЕКЦИЯ ТОВАРОВ (4 карточки) ====================

function нарисоватьСекцию(идКонтейнера, категория, режим) {
    let товары = всеТовары.filter(т => т.category === категория);

    if (режим === 'new')     товары = товары.filter(т => т.isNew);
    if (режим === 'sale')    товары = товары.filter(т => т.isSale);
    if (режим === 'popular') товары = [...товары].sort((a, b) => b.reviewCount - a.reviewCount);

    товары = товары.slice(0, 4);

    const контейнер = document.getElementById(идКонтейнера);
    if (!контейнер) return;

    if (товары.length === 0) {
        контейнер.innerHTML = '<div style="grid-column:1/-1;padding:40px;text-align:center;color:var(--текст-светлый);">Нет товаров в этой категории</div>';
        return;
    }

    контейнер.innerHTML = товары.map(т => карточкаHTML(т)).join('');

    // Обработчики кнопок
    контейнер.querySelectorAll('[data-корзина]').forEach(кн => {
        кн.addEventListener('click', e => {
            e.stopPropagation();
            const id = +кн.getAttribute('data-корзина');
            if (вКорзине(id)) { удалитьИзКорзины(id); } else { добавитьВКорзину(id); }
            нарисоватьСекцию('сетка-межком', 'interior', 'popular');
            нарисоватьСекцию('сетка-входные', 'entrance', 'popular');
        });
    });

    контейнер.querySelectorAll('[data-избранное]').forEach(кн => {
        кн.addEventListener('click', e => {
            e.stopPropagation();
            добавитьВИзбранное(+кн.getAttribute('data-избранное'));
        });
    });

    // Переход на страницу товара
    контейнер.querySelectorAll('.карточка').forEach(карточка => {
        карточка.addEventListener('click', () => {
            window.location.href = `product.html?id=${карточка.getAttribute('data-id')}`;
        });
    });
}

// HTML карточки товара
function карточкаHTML(т) {
    const скидка = т.oldPrice ? Math.round((1 - т.price / т.oldPrice) * 100) : 0;
    const вК = вКорзине(т.id);
    const вИ = вИзбранном(т.id);
    return `
    <div class="карточка" data-id="${т.id}">
        <div class="картинка-товара">
            <div class="бейджи-товара">
                ${!т.inStock ? '<span class="метка метка-нет">Нет в наличии</span>' : ''}
                ${т.isSale && скидка ? `<span class="метка метка-скидка">-${скидка}%</span>` : ''}
                ${т.isNew ? '<span class="метка метка-новинка">Новинка</span>' : ''}
            </div>
            <img src="${т.image}" alt="${т.name}" loading="lazy"
                 onerror="this.style.display='none'">
            <div class="кнопка-избранного ${вИ ? 'в-избранном' : ''}" data-избранное="${т.id}">
                ${вИ ? '♥' : '♡'}
            </div>
        </div>
        <div class="инфо-товара">
            <div class="бренд">${т.brand}</div>
            <div class="название-товара">${т.name}</div>
            <div>
                <span class="звезды">${звёзды(т.rating)}</span>
                <span class="отзывы-кол">(${т.reviewCount})</span>
            </div>
            <div class="цена-ряд">
                <div>
                    <span class="цена-текущая">${форматЦены(т.price)}</span>
                    ${т.oldPrice ? `<span class="цена-старая">${форматЦены(т.oldPrice)}</span>` : ''}
                </div>
                <div class="кнопка-корзины ${вК ? 'в-корзине' : ''}" data-корзина="${т.id}">
                    ${вК ? '✓' : '🛒'}
                </div>
            </div>
        </div>
    </div>`;
}

// ==================== ТАБЫ СЕКЦИЙ ====================

function инициализироватьТабы() {
    document.querySelectorAll('.секция-табы').forEach(группаТабов => {
        const кнопки = группаТабов.querySelectorAll('.секция-таб');
        кнопки.forEach((кнопка, индекс) => {
            кнопка.addEventListener('click', () => {
                кнопки.forEach(к => к.classList.remove('active'));
                кнопка.classList.add('active');

                // Определяем к какой сетке относится этот блок табов
                const секция = группаТабов.closest('.контейнер');
                const сетка = секция.querySelector('.сетка-главная');
                if (!сетка) return;

                const категория = сетка.id === 'сетка-межком' ? 'interior' : 'entrance';
                const режимы = ['popular', 'new', 'sale'];
                нарисоватьСекцию(сетка.id, категория, режимы[индекс]);
            });
        });
    });
}

