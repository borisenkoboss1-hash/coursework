/**
 * Отрисовывает секцию товаров по категории и режиму фильтрации
 * @param {string} идКонтейнера - ID тега, куда вставить карточки (например, "сетка-межком")
 * @param {string} категория - 'interior' или 'entrance' (из products.json поле category)
 * @param {string} режим - 'popular', 'new' или 'sale'
 * 
 * Логика фильтрации:
 * 1. Берём все товары нужной категории
 * 2. Если 'new' — оставляем только isNew === true
 * 3. Если 'sale' — оставляем только isSale === true
 * 4. Если 'popular' — сортируем по убыванию reviewCount (количество отзывов)
 * 5. Берём первые 4 товара
 * 6. Генерируем HTML через карточкаHTML() и вставляем в контейнер
 * 7. Навешиваем обработчики на кнопки "корзина" и "избранное"
 */
// ==================== СЕКЦИЯ ТОВАРОВ (4 карточки) ====================

async function нарисоватьСекцию(идКонтейнера, категория, режим) {
    // Шаг 1: фильтрация по категории
    let товары = всеТовары.filter(т => т.category === категория);

    // Шаг 2: дополнительные фильтры
    if (режим === 'new')     товары = товары.filter(т => т.isNew);
    if (режим === 'sale')    товары = товары.filter(т => т.isSale);
    if (режим === 'popular') товары = [...товары].sort((a, b) => b.reviewCount - a.reviewCount);

    товары = товары.slice(0, 4);

    const контейнер = document.getElementById(идКонтейнера);
    if (!контейнер) return;

    if (товары.length === 0) {
        контейнер.innerHTML = '<div style="grid-column:1/-1;padding:40px;text-align:center;color:var(--текст-светлый);">Нет товаров в этой категории</div>';
        return;
    }

    // 👇 ПОЛУЧАЕМ КОРЗИНУ И ИЗБРАННОЕ
    const корзина = await получитьКорзину();
    const избранное = await получитьИзбранное();

    // Создаём Set для быстрой проверки
    const корзинаIds = new Set(корзина.map(item => item.idТовара));
    const избранноеIds = new Set(избранное.map(item => item.idТовара));

    // 👇 ПЕРЕДАЁМ ПАРАМЕТРЫ В КАРТОЧКУ
    контейнер.innerHTML = товары.map(т => карточкаHTML(т, корзинаIds.has(т.id), избранноеIds.has(т.id))).join('');

    // Обработчики кнопок
    контейнер.querySelectorAll('[data-корзина]').forEach(кн => {
        кн.addEventListener('click', async e => {
            e.stopPropagation();
            const id = +кн.getAttribute('data-корзина');
            if (await вКорзине(id)) { 
                await удалитьИзКорзины(id); 
            } else { 
                await добавитьВКорзину(id); 
            }
            await нарисоватьСекцию('сетка-межком', 'interior', 'popular');
            await нарисоватьСекцию('сетка-входные', 'entrance', 'popular');
        });
    });

    контейнер.querySelectorAll('[data-избранное]').forEach(кн => {
        кн.addEventListener('click', async e => {
            e.stopPropagation();
            await добавитьВИзбранное(+кн.getAttribute('data-избранное'));
            await нарисоватьСекцию('сетка-межком', 'interior', 'popular');
            await нарисоватьСекцию('сетка-входные', 'entrance', 'popular');
        });
    });

    контейнер.querySelectorAll('.карточка').forEach(карточка => {
        карточка.addEventListener('click', () => {
            window.location.href = `product.html?id=${карточка.getAttribute('data-id')}`;
        });
    });
}

// 👇 ИСПРАВЛЕННАЯ КАРТОЧКА (принимает параметры)
function карточкаHTML(т, вК, вИ) {
    const скидка = т.oldPrice ? Math.round((1 - т.price / т.oldPrice) * 100) : 0;
    
    return `
    <div class="карточка" data-id="${т.id}">
        <div class="картинка-товара">
            <div class="бейджи-товара">
                ${!т.inStock ? '<span class="метка метка-нет">Нет в наличии</span>' : ''}
                ${т.isSale && скидка ? `<span class="метка метка-скидка">-${скидка}%</span>` : ''}
                ${т.isNew ? '<span class="метка метка-новинка">Новинка</span>' : ''}
            </div>
            <img src="${т.image}" alt="${т.name}" loading="lazy"
                 onerror="this.style.display='none'">
            <div class="кнопка-избранного ${вИ ? 'в-избранном' : ''}" data-избранное="${т.id}">
                ${вИ ? '♥' : '♡'}
            </div>
        </div>
        <div class="инфо-товара">
            <div class="бренд">${т.brand}</div>
            <div class="название-товара">${т.name}</div>
            <div>
                <span class="звезды">${звёзды(т.rating)}</span>
                <span class="отзывы-кол">(${т.reviewCount})</span>
            </div>
            <div class="цена-ряд">
                <div>
                    <span class="цена-текущая">${форматЦены(т.price)}</span>
                    ${т.oldPrice ? `<span class="цена-старая">${форматЦены(т.oldPrice)}</span>` : ''}
                </div>
                <div class="кнопка-корзины ${вК ? 'в-корзине' : ''}" data-корзина="${т.id}">
                    ${вК ? '✓' : '🛒'}
                </div>
            </div>
        </div>
    </div>`;
}

