function добавитьСсылкуДоступности() {
    // ============================================
    // ЛОГИКА ДОБАВЛЕНИЯ ССЫЛКИ ДЛЯ СЛАБОВИДЯЩИХ
    // ============================================
    // Как это работает:
    // 1. Ищем на обычной странице подвал (.низ-подвала)
    // 2. Проверяем, что мы НЕ на странице accessible.html
    //    - window.location.href — текущий URL
    //    - .includes('accessible') — содержит слово "accessible"?
    // 3. Создаём новую ссылку через document.createElement('a')
    // 4. Настраиваем её текст и стили
    // 5. Добавляем в подвал через .appendChild()
    
    var низ = document.querySelector('.низ-подвала');
    
    if (низ && !window.location.href.includes('accessible')) {
        var ссылка = document.createElement('a');
        ссылка.href = 'accessible.html';
        ссылка.textContent = '👁 Версия для слабовидящих';
        ссылка.style.cssText = 'color:#888; font-size:12px; text-decoration:none;';
        
        // ============================================
        // ЛОГИКА ИЗМЕНЕНИЯ ЦВЕТА ПРИ НАВЕДЕНИИ
        // ============================================
        // mouseenter — когда курсор мыши заходит на ссылку
        // mouseleave — когда курсор уходит со ссылки
        ссылка.addEventListener('mouseenter', function() { 
            ссылка.style.color = '#f26522';  // оранжевый
        });
        ссылка.addEventListener('mouseleave', function() { 
            ссылка.style.color = '#888';     // серый
        });
        
        низ.appendChild(ссылка);
    }
}


