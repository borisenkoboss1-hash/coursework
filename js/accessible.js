    if (!кнопка) return;  // если кнопки нет — выходим
    
    // ============================================
    // ЛОГИКА КНОПКИ СБРОСА
    // ============================================
    // При клике на кнопку сброса:
    // 1. Удаляем все ключи из localStorage (память браузера)
