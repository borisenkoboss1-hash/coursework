// ============================================================
// ЧАСТЬ 1: ПЕРЕМЕННЫЕ И НАСТРОЙКИ
// ============================================================

// localStorage — это "память" браузера.
// Когда пользователь меняет размер шрифта, мы сохраняем это число.
// При следующем заходе на сайт читаем сохранённое значение.
// Если ничего не сохранено — ставим 16px (стандартный размер).

// текущийРазмер — переменная, которая хранит размер шрифта в пикселях
// parseInt() превращает строку "16" в число 16
// '16' — значение по умолчанию, если в localStorage ничего нет
var текущийРазмер = parseInt(localStorage.getItem('а11й-размер') || '16', 10);


// ============================================================
// ЧАСТЬ 2: УПРАВЛЕНИЕ РАЗМЕРОМ ШРИФТА
// ============================================================

// Функция, которая меняет размер шрифта на всей странице
// Параметр "размер" — новое значение в пикселях (например, 18)
function применитьРазмер(размер) {
    
    // Ограничиваем размер, чтобы сайт не сломался
    // Math.max(12, ...) — если размер меньше 12, ставим 12
    // Math.min(32, ...) — если размер больше 32, ставим 32
    // То есть размер всегда будет между 12px и 32px
    текущийРазмер = Math.max(12, Math.min(32, размер));
    
    // Меняем размер шрифта у корневого элемента <html>
    // document.documentElement — это тег <html>
    // Все остальные элементы наследуют этот размер (если у них не указан свой)
    document.documentElement.style.fontSize = текущийРазмер + 'px';
    
    // Сохраняем настройку в localStorage (чтобы не сбросилась при перезагрузке)
    localStorage.setItem('а11й-размер', текущийРазмер);
    localStorage.setItem('размер-шрифта', текущийРазмер);
    
    // Обновляем выпадающий список (select) — чтобы в нём тоже было выбрано нужное значение
    var селект = document.getElementById('выбор-шрифта');
    if (селект) {
        // Ищем самый близкий вариант к текущему размеру
        var closest = null;           // сюда запишем найденный вариант
        var minDiff = 999;            // минимальная разница (начальное большое число)
        
        // Перебираем все варианты в выпадающем списке
        Array.from(селект.options).forEach(function(opt) {
            // opt.value — например, "14", "16", "20"
            // opt.value превращаем в число и считаем разницу с текущим размером
            var diff = Math.abs(parseInt(opt.value, 10) - текущийРазмер);
            
            // Если эта разница меньше предыдущей минимальной
            if (diff < minDiff) { 
                minDiff = diff;      // обновляем минимальную разницу
                closest = opt;       // запоминаем этот вариант
            }
        });
        
        // Если нашли подходящий вариант — выбираем его в списке
        if (closest) closest.selected = true;
    }
}

// Функция, которая настраивает кнопки изменения шрифта
function инициализироватьШрифт() {
    // Применяем сохранённый размер при загрузке страницы
    применитьРазмер(текущийРазмер);

    // Находим кнопку "Уменьшить шрифт" (А-)
    // addEventListener — следит за кликами на кнопку
    document.getElementById('шрифт-меньше').addEventListener('click', function() {
        // Уменьшаем на 2px (например, 16 → 14)
        применитьРазмер(текущийРазмер - 2);
    });
    
    // Находим кнопку "Увеличить шрифт" (А+)
    document.getElementById('шрифт-больше').addEventListener('click', function() {
        // Увеличиваем на 2px (например, 16 → 18)
        применитьРазмер(текущийРазмер + 2);
    });
    
    // Находим выпадающий список с размерами
    var селект = document.getElementById('выбор-шрифта');
    if (селект) {
        // Следим, когда пользователь выбирает другой вариант
        селект.addEventListener('change', function() {
            // Применяем выбранный размер (превращаем строку в число)
            применитьРазмер(parseInt(селект.value, 10));
        });
    }
}


