function инициализироватьПоискА11й() {
    // Находим поле ввода и кнопку поиска
    var поле   = document.getElementById('а11й-поле-поиска');
    var кнопка = document.getElementById('а11й-поиск-кн');
    if (!поле) return;  // если поля нет — выходим

    // ============================================
    // ЛОГИКА ПЕРЕХОДА НА СТРАНИЦУ ПОИСКА
    // ============================================
    // Как это работает:
    // 1. Пользователь вводит текст в поле поиска
    // 2. Нажимает кнопку "Найти" или клавишу Enter
    // 3. Браузер собирает значение из поля (поле.value)
    // 4. trim() удаляет лишние пробелы
    // 5. encodeURIComponent() кодирует спецсимволы (пробелы, знаки)
    //    - Например: "дверь металлическая" → "дверь%20металлическая"
    // 6. window.location.href = 'catalog.html?search=...' — перенаправляет
    //    - ?search=... — это параметр URL
    //    - Страница catalog.html прочитает этот параметр и покажет результаты
    function перейти() {
        var запрос = поле.value.trim();
        
        if (запрос) {
            // Перенаправляем на страницу catalog.html с параметром search
            // Пример: catalog.html?search=дверь
            window.location.href = 'catalog.html?search=' + encodeURIComponent(запрос);
        } else {
            // Если поле пустое — показываем сообщение и ставим курсор в поле
            уведомление('Введите поисковый запрос');
            поле.focus();  // ставим курсор мыши в поле ввода
        }
    }

    // ============================================
    // ЛОГИКА КНОПКИ "НАЙТИ"
    // ============================================
    // При клике на кнопку поиска вызываем функцию перейти()
    if (кнопка) кнопка.addEventListener('click', перейти);
    
    // ============================================
    // ЛОГИКА КЛАВИШИ ENTER
    // ============================================
    // Как браузер понимает, что нажали Enter?
    // 1. addEventListener('keypress', ...) — слушает нажатия клавиш
    // 2. Внутри функции проверяем: if (e.key === 'Enter')
    // 3. Если да — вызываем перейти()
    поле.addEventListener('keypress', function(e) {
        if (e.key === 'Enter') перейти();
    });
}


