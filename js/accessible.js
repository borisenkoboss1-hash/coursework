// - Не изменился ли адресная строка?
// 
// Когда происходит любое из этих событий, браузер:
// 1. Создаёт объект события (event)
// 2. Находит все функции, которые подписались на это событие через addEventListener
// 3. Вызывает их по очереди, передавая объект события
// 4. Ждёт следующего события
//
