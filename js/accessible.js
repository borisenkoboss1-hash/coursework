// ============================================================
// ЧТО ТАКОЕ localStorage? (ПОДРОБНОЕ ОБЪЯСНЕНИЕ)
// ============================================================
// 
// localStorage — это специальное хранилище в браузере.
// Оно работает как блокнот, который помнит информацию даже после закрытия сайта.
//
// ПРИМЕР:
// localStorage.setItem('имя', 'Иван');    // СОХРАНИТЬ
// var данные = localStorage.getItem('имя');  // ПРОЧИТАТЬ → 'Иван'
// localStorage.removeItem('имя');         // УДАЛИТЬ
//
// В НАШЕМ КОДЕ МЫ СОХРАНЯЕМ:
// - 'а11й-размер' — размер шрифта (16, 18, 20...)
// - 'а11й-тема' — цветовая тема ('normal', 'dark', 'contrast')
// - 'а11й-интервал' — межбуквенный интервал ('normal' или 'wide')
//
// ЭТО НУЖНО, ЧТОБЫ:
// Если пользователь увеличил шрифт и перешёл на другую страницу,
// шрифт остался увеличенным. Настройки НЕ СБРАСЫВАЮТСЯ!


// ============================================================
// ОБЪЯСНЕНИЕ КЛЮЧЕВЫХ КОНЦЕПЦИЙ
// ============================================================

// 1. addEventListener('click', ...)
//    - Следит за кликами на кнопку
//    - Когда пользователь нажимает — запускает указанную функцию

// 2. classList.add() / remove() / toggle()
//    - Управляют CSS-классами элементов
//    - .add('имя') — добавляет класс
//    - .remove('имя') — удаляет класс
//    - .toggle('имя', условие) — добавляет если условие true, удаляет если false

// 3. localStorage
//    - Хранилище данных в браузере
//    - Данные не удаляются при закрытии вкладки

// 4. fetch()
//    - Отправляет запрос на сервер
//    - Используется для загрузки товаров из файла products.json

// 5. async/await
//    - async — функция может ждать ответ от сервера
//    - await — жди, пока сервер ответит

// 6. .map()
//    - Преобразует массив в новый массив
//    - Например: [1,2,3].map(x => x*2) → [2,4,6]

// 7. .join('')
//    - Склеивает массив в строку
//    - Например: ['a','b','c'].join('') → 'abc'

