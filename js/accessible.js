// 3. Браузер вычисляет: какой элемент находится в этих координатах? → кнопка "шрифт-больше"
// 4. Браузер создаёт событие 'click'
// 5. Браузер вызывает функцию, которую мы передали в addEventListener
// 6. Функция выполняется: применитьРазмер(текущийРазмер + 2)
