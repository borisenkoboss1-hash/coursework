// ЧАСТЬ 4: МЕЖБУКВЕННЫЙ ИНТЕРВАЛ (РАССТОЯНИЕ МЕЖДУ БУКВАМИ)
// ============================================================

function инициализироватьИнтервал() {
    // Находим кнопки "Нормальный интервал" и "Широкий интервал"
    var норм  = document.getElementById('интервал-норм');
    var широк = document.getElementById('интервал-широк');
    
    // Если хоть одной кнопки нет на странице — выходим
    if (!норм || !широк) return;

    // ============================================
    // КАК РАБОТАЕТ МЕЖБУКВЕННЫЙ ИНТЕРВАЛ?
    // ============================================
    // В CSS есть свойство letter-spacing
    // В файле стилей определено:
    // body.интервал-широкий { letter-spacing: 0.1em; }
    // Когда мы добавляем класс "интервал-широкий" к body,
    // браузер увеличивает расстояние между всеми буквами на странице

    // Проверяем, был ли сохранён широкий интервал
    var сохр = localStorage.getItem('а11й-интервал') === 'wide';
    if (сохр) {
        // Если да — добавляем CSS-класс, который делает буквы дальше друг от друга
        document.body.classList.add('интервал-широкий');
    }

    // ============================================
    // ЛОГИКА КНОПКИ "НОРМАЛЬНЫЙ ИНТЕРВАЛ"
    // ============================================
    норм.addEventListener('click', function() {
        // Убираем широкий интервал (удаляем CSS-класс)
        document.body.classList.remove('интервал-широкий');
        // Сохраняем настройку "normal" в памяти
        localStorage.setItem('а11й-интервал', 'normal');
        // Визуально подсвечиваем активную кнопку
        норм.classList.add('active');
        широк.classList.remove('active');
    });
    
    // ============================================
    // ЛОГИКА КНОПКИ "ШИРОКИЙ ИНТЕРВАЛ"
    // ============================================
    широк.addEventListener('click', function() {
        // Добавляем широкий интервал (добавляем CSS-класс)
        document.body.classList.add('интервал-широкий');
        // Сохраняем настройку "wide" в памяти
        localStorage.setItem('а11й-интервал', 'wide');
        // Визуально подсвечиваем активную кнопку
        широк.classList.add('active');
        норм.classList.remove('active');
    });
}


