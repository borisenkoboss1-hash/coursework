// ЧАСТЬ 8: ДОБАВЛЕНИЕ ССЫЛКИ НА ОБЫЧНЫХ СТРАНИЦАХ
// ============================================================

function добавитьСсылкуДоступности() {
    // Находим подвал обычной страницы (класс .низ-подвала)
    var низ = document.querySelector('.низ-подвала');
    
    // Если подвал существует И мы не на странице accessible.html
    if (низ && !window.location.href.includes('accessible')) {
        // Создаём новую ссылку
        var ссылка = document.createElement('a');
        ссылка.href = 'accessible.html';
        ссылка.textContent = '👁 Версия для слабовидящих';
        ссылка.style.cssText = 'color:#888; font-size:12px; text-decoration:none;';
        
        // При наведении мыши — оранжевый цвет
        ссылка.addEventListener('mouseenter', function() { 
            ссылка.style.color = '#f26522'; 
        });
        // Когда убрали мышь — серый цвет
        ссылка.addEventListener('mouseleave', function() { 
            ссылка.style.color = '#888'; 
        });
        
        // Добавляем ссылку в подвал
        низ.appendChild(ссылка);
    }
}


