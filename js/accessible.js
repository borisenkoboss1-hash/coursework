// Берём сохранённую тему из памяти (по умолчанию "normal" — обычная)
var сохрТема = localStorage.getItem('а11й-тема') || 'normal';

// Функция, которая меняет цветовую тему на странице
// Параметр "тема" может быть: 'normal', 'contrast', 'dark', 'sepia'
function применитьТему(тема) {
    // Удаляем все классы тем с тела страницы
    // classList.remove() — убирает указанные CSS-классы
    // Это важно: сначала убираем все старые темы, чтобы они не конфликтовали
    document.body.classList.remove('тема-контраст', 'тема-тёмная', 'тема-сепия');
    
    // Добавляем нужный класс в зависимости от выбранной темы
    // classList.add() — добавляет CSS-класс
    // Как это работает с CSS?
    // В CSS-файле есть правила, например:
    // body.тема-тёмная { background: black; color: white; }
    // Когда мы добавляем класс "тема-тёмная", браузер переприменяет стили
    if (тема === 'contrast') document.body.classList.add('тема-контраст'); // чёрное на белом
    if (тема === 'dark')     document.body.classList.add('тема-тёмная');   // белое на чёрном
    if (тема === 'sepia')    document.body.classList.add('тема-сепия');    // бежевый фон
    
    // Сохраняем выбранную тему в localStorage
    localStorage.setItem('а11й-тема', тема);

    // Обновляем внешний вид кнопок в панели управления
    // Находим все кнопки с классом .тема-кн
    // Для каждой кнопки проверяем, совпадает ли её data-тема с выбранной
    document.querySelectorAll('.тема-кн').forEach(function(кн) {
        // Проверяем, совпадает ли тема кнопки с выбранной
        // кн.getAttribute('data-тема') — читает значение атрибута
        // Например: <button data-тема="dark"> → вернёт "dark"
        var активна = кн.getAttribute('data-тема') === тема;
        
        // classList.toggle() — добавляет класс если активно, удаляет если нет
        // Это нужно для визуальной подсветки активной кнопки
        кн.classList.toggle('active', активна);
        
        // aria-pressed — специальный атрибут для скринридеров (незрячих людей)
        // Сообщает, нажата кнопка или нет
        // Скринридер прочитает: "Тёмная тема, нажато" или "не нажато"
        кн.setAttribute('aria-pressed', String(активна));
    });
}

// Функция, которая настраивает кнопки переключения тем
function инициализироватьТемы() {
    // Применяем сохранённую тему при загрузке
    применитьТему(сохрТема);
    
    // Находим все кнопки тем и вешаем на них обработчики кликов
    document.querySelectorAll('.тема-кн').forEach(function(кн) {
        // ============================================
        // ЛОГИКА КНОПКИ ПЕРЕКЛЮЧЕНИЯ ТЕМЫ
        // ============================================
        // Когда пользователь кликает на кнопку:
        // 1. Срабатывает addEventListener
        // 2. читаем кн.getAttribute('data-тема')
        //    - Например, если нажата кнопка "Тёмная", data-тема="dark"
        // 3. вызываем применитьТему('dark')
        // 4. применитьТему меняет классы на body, сохраняет в localStorage
        // 5. Все остальные кнопки перестают быть активными
        кн.addEventListener('click', function() {
            применитьТему(кн.getAttribute('data-тема'));
        });
    });
}


