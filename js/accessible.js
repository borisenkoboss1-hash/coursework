// ЧАСТЬ 5: СБРОС ВСЕХ НАСТРОЕК ДОСТУПНОСТИ
// ============================================================

function инициализироватьСбросА11й() {
    // Находим кнопку "Сброс"
    var кнопка = document.getElementById('а11й-сброс');
    if (!кнопка) return;  // если кнопки нет — выходим
    
    // При клике на кнопку сброса
    кнопка.addEventListener('click', function() {
        // Удаляем все настройки из localStorage (памяти)
        localStorage.removeItem('а11й-размер');      // размер шрифта
        localStorage.removeItem('а11й-тема');        // цветовая тема
        localStorage.removeItem('а11й-интервал');    // межбуквенный интервал
        localStorage.removeItem('размер-шрифта');    // резервная настройка
        
        // Возвращаем значения по умолчанию
        применитьРазмер(16);                         // шрифт 16px (стандарт)
        применитьТему('normal');                     // обычная тема
        document.body.classList.remove('интервал-широкий');  // обычный интервал
        
        // Показываем всплывающее сообщение
        уведомление('Настройки доступности сброшены');
    });
}


