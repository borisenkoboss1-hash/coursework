// ЧАСТЬ 6: ПОИСК ТОВАРОВ
// ============================================================

function инициализироватьПоискА11й() {
    // Находим поле ввода и кнопку поиска
    var поле   = document.getElementById('а11й-поле-поиска');
    var кнопка = document.getElementById('а11й-поиск-кн');
    if (!поле) return;  // если поля нет — выходим

    // Внутренняя функция, которая выполняет переход на страницу с результатами
    function перейти() {
        // trim() — убирает пробелы в начале и конце
        var запрос = поле.value.trim();
        
        if (запрос) {
            // encodeURIComponent — кодирует спецсимволы (например, пробел → %20)
            // Перенаправляем на страницу catalog.html с параметром search
            // Пример: catalog.html?search=дверь
            window.location.href = 'catalog.html?search=' + encodeURIComponent(запрос);
        } else {
            // Если поле пустое — показываем сообщение и ставим курсор в поле
            уведомление('Введите поисковый запрос');
            поле.focus();  // ставим курсор мыши в поле ввода
        }
    }

    // При клике на кнопку поиска
    if (кнопка) кнопка.addEventListener('click', перейти);
    
    // При нажатии клавиши Enter в поле поиска
    поле.addEventListener('keypress', function(e) {
        // e.key === 'Enter' — нажата клавиша Enter
        if (e.key === 'Enter') перейти();
    });
}


