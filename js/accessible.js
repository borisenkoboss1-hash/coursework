// async — означает, что функция асинхронная (может ждать ответа от сервера)
async function загрузитьТоварыА11й() {
    try {
        // fetch — отправляет запрос на сервер
        // await — ждём, пока сервер ответит
        var resp = await fetch('data/products.json');
        
        // resp.json() — превращает ответ сервера в JavaScript-объект
        var товары = await resp.json();

        // Сортируем товары по рейтингу (от большего к меньшему)
        // b.rating - a.rating — если b больше a, то b встанет раньше
        var топ = товары.sort(function(a, b) { 
            return b.rating - a.rating; 
        }).slice(0, 6);  // slice(0,6) — берём первые 6 товаров
        
        var контейнер = document.getElementById('а11й-товары');
        if (!контейнер) return;  // если контейнера нет — выходим

        // Если нет ни одного товара
        if (топ.length === 0) {
            контейнер.innerHTML = '<div>Товары не загружены. Убедитесь, что сайт запущен через Live Server.</div>';
            return;
        }

        // .map() — преобразует массив товаров в массив HTML-строк
        // .join('') — соединяет все строки в одну
        контейнер.innerHTML = топ.map(function(т) {
            // Считаем скидку (если есть старая цена)
            var скидка = т.oldPrice ? Math.round((1 - т.price / т.oldPrice) * 100) : 0;
            
            // Возвращаем HTML-код одной карточки товара
            return '<a class="а11й-товар-строка" href="product.html?id=' + т.id + '" role="listitem" aria-label="' + т.name + ', цена ' + форматЦены(т.price) + '">' +
                '<div class="а11й-товар-фото" aria-hidden="true">' +
                    '<img src="' + т.image + '" alt="" loading="lazy" onerror="this.style.display=\'none\'">' +
                '</div>' +
                '<div class="а11й-товар-инфо">' +
                    '<div class="а11й-товар-бренд">' + т.brand + '</div>' +
                    '<div class="а11й-товар-назв">' + т.name + '</div>' +
                    '<div class="а11й-товар-цена">' +
                        форматЦены(т.price) +
                        (скидка ? ' <span style="font-size:0.85rem;color:var(--текст-светлый);text-decoration:line-through;">' + форматЦены(т.oldPrice) + '</span>' : '') +
                    '</div>' +
                '</div>' +
                '<button class="а11й-товар-кн" onclick="event.preventDefault(); добавитьВКорзину(' + т.id + ')" aria-label="Добавить ' + т.name + ' в корзину">В корзину</button>' +
            '</a>';
        }).join('');

    } catch(e) {
        // Если произошла ошибка (например, нет файла products.json)
        var контейнер = document.getElementById('а11й-товары');
        if (контейнер) {
            контейнер.innerHTML = '<div style="color:var(--текст-светлый);">Запустите сайт через Live Server для загрузки товаров.</div>';
        }
    }
}


