/**
 * Настраивает автоматическую маску для поля телефона
 * При вводе форматирует номер в удобный для чтения вид: +7 (999) 000-00-00
 * 
 * Логика работы:
 * 1. Удаляет все нецифровые символы
 * 2. Если начинается с 8 — заменяет на 7 (нормализация)
 * 3. Постепенно добавляет скобки, пробелы и дефисы по мере ввода цифр
 * 
 * Примеры ввода и форматирования:
 * - ввод "7" → "+7"
 * - ввод "7999" → "+7 (999"
 * - ввод "7999123" → "+7 (999) 123"
 * - ввод "79991234567" → "+7 (999) 123-45-67"
 * 
 * Источник: событие input на поле #рег-телефон
 */
function настроитьМаскуТелефона() {
    const поле = document.getElementById('рег-телефон');
    if (!поле) return;
    
    поле.addEventListener('input', () => {
        // 1. Оставляем только цифры
        let значение = поле.value.replace(/\D/g, '');
        
        // 2. Нормализуем: 8 → 7 (международный формат)
        if (значение.startsWith('8')) значение = '7' + значение.slice(1);
        
        // 3. Строим форматированную строку, только если начинается с 7
        if (значение.startsWith('7')) {
            let форматированный = '+7';
            
            // Скобки и пробел после +7
            if (значение.length > 1) форматированный += ' (' + значение.slice(1, 4);
            // Закрываем скобку и добавляем пробел
            if (значение.length >= 4) форматированный += ') ' + значение.slice(4, 7);
            // Дефис после 7 цифр
            if (значение.length >= 7) форматированный += '-' + значение.slice(7, 9);
            // Второй дефис после 9 цифр
            if (значение.length >= 9) форматированный += '-' + значение.slice(9, 11);
            
            поле.value = форматированный;
        }
    });
}

