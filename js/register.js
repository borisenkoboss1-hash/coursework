/**
 * Настраивает кнопки-глазики для переключения видимости пароля
 * Работает для двух полей: пароль и подтверждение пароля
 * 
 * Логика:
 * - Находит кнопку и поле ввода
 * - По клику меняет type у поля: 'password' ↔ 'text'
 * - Меняет иконку кнопки: 👁 (глаз) ↔ 🙈 (глаз зачёркнут)
 * 
 * Источник DOM-элементов: HTML должен содержать кнопки с ID:
 * - 'показать-пароль' и поле 'рег-пароль'
 * - 'показать-пароль2' и поле 'рег-пароль2'
 */
function настроитьКнопкиПоказатьПароль() {
    // Массив пар [ID кнопки, ID поля ввода]
    [['показать-пароль', 'рег-пароль'], ['показать-пароль2', 'рег-пароль2']].forEach(([идКн, идПоля]) => {
        const кн = document.getElementById(идКн);
        const поле = document.getElementById(идПоля);
        if (!кн || !поле) return;
        
        кн.addEventListener('click', () => {
            const скрыт = поле.type === 'password';
            // Меняем тип поля: если был password → text (показываем), и наоборот
            поле.type = скрыт ? 'text' : 'password';
            // Меняем иконку: 👁 (глаз) — показать, 🙈 (закрытый глаз) — скрыть
            кн.textContent = скрыт ? '🙈' : '👁';
        });
    });
}

