/**
 * Обработчик отправки формы регистрации
 * @param {Event} событие - событие submit формы
 * 
 * Полный цикл:
 * 1. Отменяет стандартную отправку (чтобы страница не перезагружалась)
 * 2. Валидирует все поля (вызывает проверитьПоле для каждого)
 * 3. Проверяет согласие (чекбокс)
 * 4. Если есть ошибки — прерывает выполнение
 * 5. Загружает users.json для проверки уникальности email
 * 6. Если email уже существует — показывает ошибку
 * 7. Создаёт объект нового пользователя
 * 8. Сохраняет в localStorage (имитация серверной регистрации)
 * 9. Показывает уведомление об успехе
 * 10. Блокирует кнопку и через 1.2 секунды перенаправляет на главную
 * 
 * Источники данных:
 * - Поля формы (DOM)
 * - users.json (статический файл с зарегистрированными пользователями)
 * 
 * Куда сохраняется: localStorage (ключ 'пользователь')
 */
async function отправитьФорму(событие) {
    // Отменяем стандартное поведение формы (перезагрузку страницы)
    событие.preventDefault();

    // ===== ШАГ 1: ВАЛИДАЦИЯ ВСЕХ ПОЛЕЙ =====
    // Проверяем каждое поле, собираем результаты (true = ошибок нет)
    const результаты = [
        проверитьПоле('рег-имя',      правила.имя),
        проверитьПоле('рег-email',    правила.email),
        проверитьПоле('рег-телефон',  правила.телефон),
        проверитьПоле('рег-пароль',   правила.пароль),
        проверитьПоле('рег-пароль2',  правила.пароль2),
    ];

    // ===== ШАГ 2: ПРОВЕРКА СОГЛАСИЯ (чекбокс) =====
    // У чекбокса нет отдельного элемента-поля, проверяем отдельно
    const согласие = document.getElementById('рег-согласие');
    const ошибкаСогл = document.getElementById('ошибка-согласие');
    const согласиеОК = согласие.checked;
    
    if (!согласиеОК) {
        ошибкаСогл.textContent = 'Необходимо согласие с условиями';
    } else {
        ошибкаСогл.textContent = '';
    }
    результаты.push(согласиеОК);

    // Если хотя бы одна проверка не пройдена (false) — останавливаем отправку
    if (результаты.includes(false)) {
        return;  // Прерываем выполнение, форма не отправляется
    }

    // ===== ШАГ 3: ПРОВЕРКА УНИКАЛЬНОСТИ EMAIL (через json-server) =====
    try {
        const emailПоле = document.getElementById('рег-email');
        const email = emailПоле.value.trim();

        // Делаем GET-запрос с фильтром по email прямо в URL —
        // json-server вернёт массив (0 или 1 элемент), а не весь список пользователей
        const проверка = await fetch(API_URL + '/users?email=' + encodeURIComponent(email));
        const найденные = await проверка.json();

        if (найденные.length > 0) {
            // Email уже занят — показываем ошибку
            показатьСтатусПоля(emailПоле, document.getElementById('ошибка-email'), 'Этот email уже зарегистрирован');
            return;  // Прерываем регистрацию
        }

        // ===== ШАГ 4: СОЗДАНИЕ НОВОГО ПОЛЬЗОВАТЕЛЯ =====
        // Собираем данные из формы. id НЕ указываем — json-server сгенерирует его сам
        const новыйПользователь = {
            name: document.getElementById('рег-имя').value.trim(),
            email: email,
            password: document.getElementById('рег-пароль').value,  // В реальном проекте — хешировать!
            phone: document.getElementById('рег-телефон').value.trim(),
            role: 'user',                                      // Права доступа: обычный пользователь
            avatar: `https://i.pravatar.cc/150?u=${Date.now()}`, // Генерируем аватар сервисом pravatar
            createdAt: new Date().toISOString().split('T')[0]   // Текущая дата в формате ГГГГ-ММ-ДД
        };

        // ===== ШАГ 5: СОХРАНЕНИЕ НА СЕРВЕРЕ =====
        // POST-запрос создаёт нового пользователя в коллекции users
        const ответ = await fetch(API_URL + '/users', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(новыйПользователь)
        });

        if (!ответ.ok) throw new Error('Ошибка сервера при регистрации');

        // Сервер возвращает созданного пользователя — уже с присвоенным id
        const сохранённыйПользователь = await ответ.json();

        // Сохраняем в localStorage только как "текущая сессия" —
        // источник правды — сервер, localStorage просто запоминает кто вошёл
        localStorage.setItem('пользователь', JSON.stringify(сохранённыйПользователь));

        // Показываем успешное уведомление
        уведомление('Регистрация прошла успешно! Добро пожаловать!', 'успех');

        // ===== ШАГ 6: БЛОКИРОВКА КНОПКИ И ПЕРЕНАПРАВЛЕНИЕ =====
        // Блокируем кнопку, чтобы пользователь не нажал дважды
        const кнопка = document.getElementById('кнопка-регистрации');
        кнопка.disabled = true;
        кнопка.textContent = '✓ Готово!';
        
        // Через 1.2 секунды переходим на главную страницу
        // Задержка нужна, чтобы пользователь успел увидеть уведомление и надпись на кнопке
        setTimeout(() => window.location.href = 'index.html', 1200);

    } catch (e) {
        // ===== ОБРАБОТКА ОШИБОК =====
        // Если users.json не загрузился, нет интернета или другая ошибка
        уведомление('Ошибка при регистрации. Попробуйте позже.', 'ошибка');
        console.error('Ошибка регистрации:', e);
    }
}

