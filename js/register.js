/**
 * Инициализация страницы после загрузки DOM
 * 
 * Настройка:
 * 1. Кнопки показа/скрытия пароля (глазики)
 * 2. Маска для телефона
 * 3. Обработчики валидации на blur (потеря фокуса) и input (ввод)
 * 4. Обработчик отправки формы
 */
document.addEventListener('DOMContentLoaded', () => {
    // Настройка UI-компонентов
    настроитьКнопкиПоказатьПароль();
    настроитьМаскуТелефона();

    // ===== ВАЛИДАЦИЯ В РЕАЛЬНОМ ВРЕМЕНИ =====
    // Событие 'blur' (потеря фокуса) — проверяем поле, показываем ошибку сразу после того, как пользователь перешёл к следующему полю
    
    // Имя — проверяем при потере фокуса
    document.getElementById('рег-имя')?.addEventListener('blur', () => проверитьПоле('рег-имя', правила.имя));
    
    // Email — при потере фокуса
    document.getElementById('рег-email')?.addEventListener('blur', () => проверитьПоле('рег-email', правила.email));
    
    // Телефон — при потере фокуса
    document.getElementById('рег-телефон')?.addEventListener('blur', () => проверитьПоле('рег-телефон', правила.телефон));
    
    // Пароль — проверяем при вводе (input), но только если введено больше 3 символов
    // Это улучшает UX: не показываем красную рамку сразу после первого символа
    document.getElementById('рег-пароль')?.addEventListener('input', () => {
        обновитьСилуПароля();  // Обновляем индикатор силы пароля
        const поле = document.getElementById('рег-пароль');
        if (поле.value.length > 3) {  // Ждём 4+ символов для проверки
            проверитьПоле('рег-пароль', правила.пароль);
        }
    });
    
    // Подтверждение пароля — проверяем при каждом вводе (сразу видно, совпадает или нет)
    document.getElementById('рег-пароль2')?.addEventListener('input', () => проверитьПоле('рег-пароль2', правила.пароль2));

    // ===== ОТПРАВКА ФОРМЫ =====
    // Подписываемся на событие submit — срабатывает при нажатии на кнопку "Зарегистрироваться"
    document.getElementById('форма-регистрации')?.addEventListener('submit', отправитьФорму);
});