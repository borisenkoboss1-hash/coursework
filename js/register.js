// ==================== ВАЛИДАЦИЯ ПОЛЕЙ ====================
// Объект с правилами валидации для каждого поля
// Каждая функция принимает значение поля и возвращает:
// - пустую строку, если ошибок нет
// - текст ошибки, если есть проблема
//
// Источник данных: значение из input (пользовательский ввод)
// Куда передаётся: в функции проверитьПоле() и показатьСтатусПоля()
const правила = {
    /**
     * Валидация имени и фамилии
     * @param {string} значение - значение из поля ввода
     * @returns {string} - текст ошибки или '' если всё правильно
     * 
     * Требования:
     * - Не пустое
     * - Минимум 2 слова (имя и фамилия)
     * - Только буквы (русские/английские), пробелы и дефисы
     */
    имя(значение) {
        if (!значение) return 'Введите имя и фамилию';
        // split(/\s+/) — разбиваем по пробелам, trim() убирает пробелы по краям
        if (значение.trim().split(/\s+/).length < 2) return 'Введите имя и фамилию через пробел';
        // Регулярка: русские и английские буквы + пробел + дефис
        if (!/^[а-яёА-ЯЁa-zA-Z\s-]+$/.test(значение)) return 'Только буквы, пробел и дефис';
        return '';
    },
    
    /**
     * Валидация email
     * @param {string} значение - email пользователя
     * @returns {string} - ошибка или ''
     * 
     * Формат: любое_имя@любой_домен.любая_зона
     * [^\s@] — любой символ, кроме пробела и @
     */
    email(значение) {
        if (!значение) return 'Введите email';
        if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(значение)) return 'Неверный формат email';
        return '';
    },
    
    /**
     * Валидация российского номера телефона
     * @param {string} значение - номер телефона (с пробелами, скобками, дефисами)
     * @returns {string} - ошибка или ''
     * 
     * Принимает форматы:
     * - +7 999 123 45 67
     * - 8 (999) 123-45-67
     * - +7(999)1234567
     * После очистки от нецифровых символов должно быть: +7XXXXXXXXXX или 8XXXXXXXXXX
     */
    телефон(значение) {
        if (!значение) return 'Введите телефон';
        // Удаляем всё, кроме цифр: пробелы, скобки, дефисы, плюсы
        const чистый = значение.replace(/[\s\-()]/g, '');
        // Должно начинаться с +7 или 8, затем ровно 10 цифр
        if (!/^(\+7|8)\d{10}$/.test(чистый)) return 'Формат: +7 (999) 000-00-00';
        return '';
    },
    
    /**
     * Валидация пароля
     * @param {string} значение - пароль
     * @returns {string} - ошибка или ''
     * 
     * Требования:
     * - Минимум 6 символов
     * - Хотя бы одна цифра
     * - Хотя бы одна буква (латиница или кириллица)
     */
    пароль(значение) {
        if (!значение) return 'Введите пароль';
        if (значение.length < 6) return 'Минимум 6 символов';
        if (!/\d/.test(значение)) return 'Пароль должен содержать цифру';
        if (!/[a-zA-Zа-яА-Я]/.test(значение)) return 'Пароль должен содержать букву';
        return '';
    },
    
    /**
     * Проверка подтверждения пароля
     * @param {string} значение - повторно введённый пароль
     * @returns {string} - ошибка или ''
     * 
     * ДОСТУП К ДРУГОМУ ПОЛЮ: читает значение из DOM по ID 'рег-пароль'
     * Это НЕ чистая функция (зависит от внешнего состояния)
     */
    пароль2(значение) {
        const пароль = document.getElementById('рег-пароль').value;
        if (!значение) return 'Повторите пароль';
        if (значение !== пароль) return 'Пароли не совпадают';
        return '';
    },
    
    /**
     * Проверка согласия с условиями
     * @returns {string} - ошибка, если чекбокс не отмечен
     * 
     * Не принимает аргумент, потому что считывает состояние чекбокса напрямую
     */
    согласие() {
        if (!document.getElementById('рег-согласие').checked) return 'Необходимо согласие';
        return '';
    }
};

/**
 * Отображает статус валидации для одного поля
 * @param {HTMLElement} поле - DOM-элемент input
 * @param {HTMLElement} ошибкаЭл - элемент для вывода текста ошибки
 * @param {string} ошибка - текст ошибки (пустая строка, если всё ОК)
 * 
 * Логика:
 * - Добавляет/убирает CSS-классы 'ошибка' и 'успех' (меняют цвет границы)
 * - Отображает текст ошибки под полем
 * 
 * Куда передаются результаты: визуально в DOM (пользователь видит)
 */
function показатьСтатусПоля(поле, ошибкаЭл, ошибка) {
    if (ошибка) {
        // Если есть ошибка — красная рамка, показываем текст
        поле.classList.add('ошибка');
        поле.classList.remove('успех');
        ошибкаЭл.textContent = ошибка;
    } else {
        // Если ошибок нет — зелёная рамка, скрываем текст
        поле.classList.remove('ошибка');
        поле.classList.add('успех');
        ошибкаЭл.textContent = '';
    }
}

/**
 * Проверяет одно поле по заданному правилу
 * @param {string} идПоля - ID элемента input (например, 'рег-имя')
 * @param {Function} правило - функция валидации из объекта правила
 * @returns {boolean} - true, если ошибок нет, false если есть
 * 
 * Логика:
 * 1. Находит поле и элемент для ошибки по ID
 * 2. Получает значение поля (trim — убираем пробелы по краям)
 * 3. Вызывает функцию правила (получает текст ошибки или '')
 * 4. Обновляет визуальный статус
 * 5. Возвращает true/false (нужно для итоговой проверки формы)
 */
function проверитьПоле(идПоля, правило) {
    const поле = document.getElementById(идПоля);
    // Строим ID элемента для ошибки: 'рег-имя' → 'ошибка-имя'
    const ошибкаЭл = document.getElementById('ошибка-' + идПоля.replace('рег-', ''));
    if (!поле || !ошибкаЭл) return true;
    
    const ошибка = правило(поле.value.trim());
    показатьСтатусПоля(поле, ошибкаЭл, ошибка);
    return !ошибка;  // true = нет ошибки, false = есть ошибка
}

// ==================== СИЛА ПАРОЛЯ ====================

/**
 * Вычисляет сложность пароля по балльной системе
 * @param {string} пароль - введённый пароль
 * @returns {number} - число от 0 до 5 (количество выполненных критериев)
 * 
 * Критерии (каждый даёт +1 балл):
 * 1. Длина >= 6 символов
 * 2. Длина >= 10 символов (бонус за длинный пароль)
 * 3. Содержит цифру
 * 4. Содержит заглавную букву (латиницу или кириллицу)
 * 5. Содержит спецсимвол (!@#$%^&*)
 */
function вычислитьСилуПароля(пароль) {
    let сила = 0;
    if (пароль.length >= 6)  сила++;
    if (пароль.length >= 10) сила++;
    if (/\d/.test(пароль))   сила++;
    // [A-Z] — английские заглавные, [А-Я] — русские заглавные
    if (/[A-Z]/.test(пароль) || /[А-Я]/.test(пароль)) сила++;
    if (/[!@#$%^&*]/.test(пароль)) сила++;
    return сила;
}

/**
 * Обновляет визуальный индикатор силы пароля
 * Читает текущий пароль, вычисляет силу, меняет ширину полоски, цвет и текст
 * 
 * DOM-элементы, которые обновляются:
 * - #сила-полоска (ширина и цвет фона)
 * - #сила-текст (текст и цвет)
 * 
 * Отображаемые уровни (от 0 до 5 баллов):
 * 0-1: Очень слабый (красный, 20%)
 * 2: Слабый (оранжевый, 40%)
 * 3: Средний (желтый, 60%)
 * 4: Хороший (зеленый, 80%)
 * 5: Отличный (бирюзовый, 100%)
 */
function обновитьСилуПароля() {
    const пароль = document.getElementById('рег-пароль').value;
    const полоска = document.getElementById('сила-полоска');
    const текст = document.getElementById('сила-текст');
    if (!полоска) return;  // Если индикатора нет на странице — выходим

    // Если пароль пустой — сбрасываем индикатор
    if (!пароль) { 
        полоска.style.width = '0'; 
        текст.textContent = ''; 
        return; 
    }

    const сила = вычислитьСилуПароля(пароль);
    
    // Маппинг баллов в визуальные параметры
    // Math.min(сила - 1, 4) превращает 1→0, 2→1, 3→2, 4→3, 5→4
    // Если сила = 0, уровень[0] (по умолчанию)
    const уровни = [
        { ширина: '20%', цвет: '#e74c3c', текст: 'Очень слабый' },   // 0-1 балл
        { ширина: '40%', цвет: '#e67e22', текст: 'Слабый' },         // 2 балла
        { ширина: '60%', цвет: '#f39c12', текст: 'Средний' },        // 3 балла
        { ширина: '80%', цвет: '#27ae60', текст: 'Хороший' },        // 4 балла
        { ширина: '100%', цвет: '#1abc9c', текст: 'Отличный' },      // 5 баллов
    ];
    
    const уровень = уровни[Math.min(сила - 1, 4)] || уровни[0];
    
    // Применяем стили
    полоска.style.width = уровень.ширина;
    полоска.style.background = уровень.цвет;
    текст.textContent = уровень.текст;
    текст.style.color = уровень.цвет;
}

