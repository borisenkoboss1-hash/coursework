/* ========================================================
   register.js — логика регистрации с валидацией
   
   Что делает этот файл:
   - Проверяет корректность вводимых данных в реальном времени
   - Отображает силу пароля (полоска + текст)
   - Предоставляет маску ввода для телефона
   - Позволяет показать/скрыть пароль (глазик)
   - Отправляет данные регистрации после успешной валидации
   - Проверяет email на уникальность (из users.json)
   - Сохраняет пользователя в localStorage и перенаправляет на главную
   ======================================================== */

