// ЧАСТЬ 5: ОБНОВЛЕНИЕ СЧЁТЧИКОВ (цифры у иконок корзины и избранного в шапке)
// ════════════════════════════════════════════════════════════════════════════════════════════════════════════

function обновитьСчётчики() {
    var сК = document.getElementById('счетчик-корзины');
    var сИ = document.getElementById('счетчик-избранного');
    
    // Считаем ОБЩЕЕ КОЛИЧЕСТВО товаров (сумма количеств)
    const корзина = получитьКорзину();
    const общееКоличество = корзина.reduce(function(сумма, т) {
        return сумма + (т.количество || 1);
    }, 0);
    
    if (сК) сК.textContent = общееКоличество;
    if (сИ) сИ.textContent = получитьИзбранное().length;
}


