// Функция получает уникальный ID текущего пользователя
// Возвращает: строку вида "телефон_email" или null, если пользователь не залогинен
function получитьIdПользователяДляКлюча() {
    // 1. Получаем объект пользователя из localStorage
    const пользователь = получитьПользователя();
    
    // 2. Если пользователь не залогинен — возвращаем null
    //    (корзина НЕ сохраняется для гостей!)
    if (!пользователь) return null;
    
    // 3. Берём телефон, email и имя (для уникальности)
    const телефон = пользователь.phone || '';
    const email = пользователь.email || '';
    const имя = пользователь.name || '';
    
    // 4. Собираем непустые части в массив
    const части = [телефон, email, имя].filter(ч => ч !== '');
    
    // 5. Если всё пусто (не должно быть) — генерируем временный ID
    if (части.length === 0) return 'unknown_' + Date.now();
    
    // 6. Склеиваем через нижнее подчёркивание
    return части.join('_');
}

