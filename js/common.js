// ПОЛУЧЕНИЕ ИЗБРАННОГО ТЕКУЩЕГО ПОЛЬЗОВАТЕЛЯ
function получитьИзбранное() {
    const userId = получитьIdПользователяДляКлюча();
    if (!userId) return [];
    
    // ✅ КЛЮЧ ЗАВИСИТ ОТ ПОЛЬЗОВАТЕЛЯ!
    const ключ = `избранное_${userId}`;
    const данные = localStorage.getItem(ключ);
    return данные ? JSON.parse(данные) : [];
}

// СОХРАНЕНИЕ ИЗБРАННОГО ТЕКУЩЕГО ПОЛЬЗОВАТЕЛЯ
function сохранитьИзбранное(избранное) {
    const userId = получитьIdПользователяДляКлюча();
    if (!userId) return false;
    
    const ключ = `избранное_${userId}`;
    localStorage.setItem(ключ, JSON.stringify(избранное));
    return true;
}

// ПРОВЕРКА НАЛИЧИЯ ТОВАРА В ИЗБРАННОМ
function вИзбранном(id) {
    return получитьИзбранное().some(function(т) { return т.idТовара === id; });
}

// ДОБАВЛЕНИЕ/УДАЛЕНИЕ ТОВАРА В ИЗБРАННОЕ (функция-переключатель)
function добавитьВИзбранное(id) {
    // 1. Проверяем авторизацию
    var польз = получитьПользователя();
    if (!польз) {
        уведомление('Войдите в аккаунт', 'ошибка');
        открытьМодалкуВхода();
        return false;
    }
    
    // 2. Если товар уже в избранном — удаляем его
    if (вИзбранном(id)) {
        var изб1 = получитьИзбранное().filter(function(т) { return т.idТовара !== id; });
        сохранитьИзбранное(изб1);
        обновитьСчётчики();
        уведомление('Удалено из избранного');
        return false;
    }
    
    // 3. Если товара нет — добавляем
    var изб2 = получитьИзбранное();
    изб2.push({
        idТовара: id
    });
    сохранитьИзбранное(изб2);
    обновитьСчётчики();
    уведомление('Добавлено в избранное ♡', 'успех');
    return true;
}


