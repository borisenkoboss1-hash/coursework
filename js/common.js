// РЕЖИМ ДОСТУПНОСТИ (ДЛЯ СЛАБОВИДЯЩИХ)
// ============================================================
// Эта функция:
// 1. Восстанавливает сохранённые настройки доступности при загрузке страницы
// 2. Настраивает кнопку для включения/выключения режима доступности
// 3. Режим доступности меняет стили сайта для удобства слабовидящих:
//    - Увеличивает шрифт
//    - Увеличивает контрастность
//    - Увеличивает отступы и кнопки

function инициализироватьДоступность() {
    
    // ============================================================
    // ШАГ 1: ВОССТАНОВЛЕНИЕ СОХРАНЁННОГО РЕЖИМА ДОСТУПНОСТИ
    // ============================================================
    
    // localStorage.getItem('доступность') — читаем настройку из памяти браузера
    // Если сохранено значение 'true' — значит пользователь ранее включил режим доступности
    // и при повторном заходе на сайт его нужно включить снова
    if (localStorage.getItem('доступность') === 'true') {
        // document.body — это тег <body> на странице
        // setAttribute('data-a11y', 'true') — добавляет атрибут data-a11y="true" к <body>
        // CSS стили используют этот атрибут для применения специальных стилей:
        // body[data-a11y="true"] { font-size: 18px; line-height: 1.5; }
        // body[data-a11y="true"] button { padding: 12px 24px; font-size: 18px; }
        document.body.setAttribute('data-a11y', 'true');
    }
    
    // ============================================================
    // ШАГ 2: ВОССТАНОВЛЕНИЕ СОХРАНЁННОГО РАЗМЕРА ШРИФТА
    // ============================================================
    
    // localStorage.getItem('размер-шрифта') — читаем сохранённый размер шрифта
    // Например: '16', '18', '20', '24', '28', '32'
    var размер = localStorage.getItem('размер-шрифта');
    
    // Если размер был сохранён (не null, не пустая строка)
    if (размер) {
        // document.documentElement — это тег <html> (корневой элемент страницы)
        // style.fontSize — устанавливаем CSS-свойство font-size для всего документа
        // Все элементы наследуют этот размер, если у них не указан свой
        // Например: document.documentElement.style.fontSize = '20px';
        document.documentElement.style.fontSize = размер + 'px';
    }
    
    // ============================================================
    // ШАГ 3: НАХОДИМ КНОПКУ ВКЛЮЧЕНИЯ/ВЫКЛЮЧЕНИЯ РЕЖИМА ДОСТУПНОСТИ
    // ============================================================
    
    // document.getElementById('кнопка-доступности') — ищет элемент с id="кнопка-доступности"
    // Это кнопка с изображением глаза 👁 в шапке сайта
    var кнопка = document.getElementById('кнопка-доступности');
    
    // Если кнопка не найдена на странице — выходим из функции (ничего не делаем)
    // Например, на страницах, где нет этой кнопки
    if (!кнопка) return;
    
    // ============================================================
    // ШАГ 4: НАСТРАИВАЕМ ПОВЕДЕНИЕ КНОПКИ ПРИ КЛИКЕ
    // ============================================================
    
    // При клике на кнопку  выполняется эта функция
    кнопка.onclick = function() {
        
        // Проверяем, включён ли сейчас режим доступности
        // document.body.getAttribute('data-a11y') — читаем значение атрибута
        // Если data-a11y="true" → режим включён → включён = true
        // Если атрибута нет или он не равен 'true' → режим выключен → включён = false
        var включён = document.body.getAttribute('data-a11y') === 'true';
        
        // ============================================================
        // СЛУЧАЙ 1: РЕЖИМ ДОСТУПНОСТИ ВКЛЮЧЁН → ВЫКЛЮЧАЕМ ЕГО
        // ============================================================
        
        if (включён) {
            // Удаляем атрибут data-a11y с тега <body>
            // При этом CSS-стили для режима доступности перестают применяться
            document.body.removeAttribute('data-a11y');
            
            // Сохраняем в localStorage, что режим доступности выключен
            // При следующей загрузке страницы прочитаем 'false' и не включим режим
            localStorage.setItem('доступность', 'false');
            
            // Показываем уведомление пользователю, что режим выключен
            уведомление('Режим доступности выключен');
        } 
        
        // ============================================================
        // СЛУЧАЙ 2: РЕЖИМ ДОСТУПНОСТИ ВЫКЛЮЧЁН - ВКЛЮЧАЕМ ЕГО
        // ============================================================
        
        else {
            // Добавляем атрибут data-a11y="true" к тегу <body>
            // CSS-стили для режима доступности начинают применяться:
            // - Увеличивается шрифт
            // - Увеличиваются кнопки и отступы
            // - Повышается контрастность
            document.body.setAttribute('data-a11y', 'true');
            
            // Сохраняем в localStorage, что режим доступности включён
            // При следующей загрузке страницы прочитаем 'true' и снова включим режим
            localStorage.setItem('доступность', 'true');
            
            // Показываем уведомление пользователю, что режим включён
            уведомление('Режим доступности включён');
        }
    };
}

