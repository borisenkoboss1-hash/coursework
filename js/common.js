// Функция загружает сохранённую тему при загрузке страницы и настраивает кнопку переключения
function инициализироватьТему() {
    // ШАГ 1: ВОССТАНОВЛЕНИЕ СОХРАНЁННОЙ ТЕМЫ
    // localStorage.getItem('тема') — читаем настройку темы из памяти браузера
    // Если сохранено значение 'dark' — значит пользователь выбрал тёмную тему
    if (localStorage.getItem('тема') === 'dark') {
        // document.body — это тег <body> на странице
        // setAttribute('data-theme', 'dark') — добавляет атрибут data-theme="dark" к <body>
        // CSS стили используют этот атрибут для переключения цветов:
        // body[data-theme="dark"] { background: black; color: white; }
        document.body.setAttribute('data-theme', 'dark');
    }
    
    // ШАГ 2: ОБНОВЛЕНИЕ ТЕКСТА КНОПКИ
    // обновитьКнопкуТемы() — меняет текст кнопки на "☀ Светлая" или "☾ Тёмная"
    обновитьКнопкуТемы();
    
    // ШАГ 3: НАХОДИМ КНОПКУ ПЕРЕКЛЮЧЕНИЯ ТЕМЫ НА СТРАНИЦЕ
    // document.getElementById('кнопка-темы') — ищет элемент с id="кнопка-темы"
    var кнопка = document.getElementById('кнопка-темы');
    
    // Если кнопка не найдена на странице — выходим из функции (ничего не делаем)
    if (!кнопка) return;
    
    // ШАГ 4: НАСТРАИВАЕМ ОБРАБОТЧИК КЛИКА НА КНОПКУ
    // При клике на кнопку будет выполняться функция внутри
    кнопка.onclick = function() {
        // Проверяем, какая тема сейчас активна
        // document.body.getAttribute('data-theme') — читаем значение атрибута
        // Если data-theme="dark", то тёмная тема включена → тёмная = true
        var тёмная = document.body.getAttribute('data-theme') === 'dark';
        
        if (тёмная) {
            // Если сейчас ТЁМНАЯ тема → ПЕРЕКЛЮЧАЕМ НА СВЕТЛУЮ
            
            // removeAttribute('data-theme') — удаляем атрибут с тегом <body>
            // При отсутствии атрибута применяются стандартные светлые стили
            document.body.removeAttribute('data-theme');
            
            // Сохраняем выбор пользователя в localStorage (ключ 'тема', значение 'light')
            localStorage.setItem('тема', 'light');
        } else {
            // Если сейчас СВЕТЛАЯ тема → ПЕРЕКЛЮЧАЕМ НА ТЁМНУЮ
            
            // setAttribute('data-theme', 'dark') — добавляем атрибут к <body>
            // CSS стили применяют тёмную тему
            document.body.setAttribute('data-theme', 'dark');
            
            // Сохраняем выбор пользователя в localStorage (ключ 'тема', значение 'dark')
            localStorage.setItem('тема', 'dark');
        }
        
        // ШАГ 5: ОБНОВЛЯЕМ ТЕКСТ КНОПКИ ПОСЛЕ ПЕРЕКЛЮЧЕНИЯ
        // Теперь кнопка показывает противоположное действие
        // Например: если тема стала тёмной, кнопка показывает "☀ Светлая"
        обновитьКнопкуТемы();
    };
}
// Обновляет текст на кнопке переключения темы
function обновитьКнопкуТемы() {
    var кнопка = document.getElementById('кнопка-темы');
    if (!кнопка) return;
    // Текст зависит от текущей темы
    кнопка.textContent = document.body.getAttribute('data-theme') === 'dark' ? '☀ Светлая' : '☾ Тёмная';
}

