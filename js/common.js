// ЧАСТЬ 3: РАБОТА С КОРЗИНОЙ (СЕРВЕР)
// ============================================================

async function получитьКорзину() {
    const userId = getCurrentUserId();
    if (!userId) return [];
    
    try {
        const response = await fetch(`${API_URL}/cart`);
        const всеЗаписи = await response.json();
        // Фильтруем по idПользователя
        return всеЗаписи.filter(item => item.idПользователя === userId);
    } catch (error) {
        console.error('Ошибка загрузки корзины:', error);
        return [];
    }
}

async function добавитьВКорзину(idТовара) {
    const user = получитьПользователя();
    if (!user) {
        уведомление('Войдите в аккаунт', 'ошибка');
        открытьМодалкуВхода();
        return false;
    }
    
    try {
        const корзина = await получитьКорзину();
        const существующий = корзина.find(item => item.idТовара === idТовара);
        
        if (существующий) {
            await fetch(`${API_URL}/cart/${существующий.id}`, {
                method: 'PUT',
                headers: getHeaders(),
                body: JSON.stringify({ 
                    ...существующий, 
                    количество: существующий.количество + 1 
                })
            });
        } else {
            const новыйId = Date.now();
            await fetch(`${API_URL}/cart`, {
                method: 'POST',
                headers: getHeaders(),
                body: JSON.stringify({
                    id: новыйId,
                    idПользователя: user.id,
                    idТовара: idТовара,
                    количество: 1
                })
            });
        }
        
        обновитьСчётчики();
        уведомление('Товар добавлен в корзину', 'успех');
        return true;
    } catch (error) {
        console.error('Ошибка добавления в корзину:', error);
        уведомление('Ошибка сервера', 'ошибка');
        return false;
    }
}

async function удалитьИзКорзины(idТовара) {
    try {
        const корзина = await получитьКорзину();
        const запись = корзина.find(item => item.idТовара === idТовара);
        if (запись) {
            await fetch(`${API_URL}/cart/${запись.id}`, { method: 'DELETE' });
        }
        обновитьСчётчики();
        уведомление('Товар удалён из корзины');
    } catch (error) {
        console.error('Ошибка удаления из корзины:', error);
        уведомление('Ошибка сервера', 'ошибка');
    }
}

