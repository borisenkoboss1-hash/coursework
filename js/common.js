// Функция форматирует число в цену с пробелами и знаком рубля
// Пример: 15000 → "15 000 ₽"
function форматЦены(число) {
    // toLocaleString('ru-RU') — добавляет пробелы между разрядами
    return Number(число).toLocaleString('ru-RU') + ' ₽';
}

// Функция превращает число (рейтинг) в звёзды
// Пример: 4.5 → "★★★★½" (4 полных звезды и половина)
function звёзды(рейтинг) {
    let html = '';
    // Цикл от 1 до 5, сравниваем с округлённым рейтингом
    for (let i = 1; i <= 5; i++) {
        html += i <= Math.round(рейтинг) ? '★' : '☆';
    }
    return html;
}

// Функция показывает всплывающее уведомление (в правом нижнем углу)
// тип может быть: 'успех' (зелёный), 'ошибка' (красный), 'info' (серый)
function уведомление(текст, тип) {
    тип = тип || 'info';  // если тип не указан, используем 'info'
    const контейнер = document.getElementById('контейнер-уведомлений');
    if (!контейнер) return;  // если контейнера нет — выходим
    
    // Создаём новый элемент уведомления
    const блок = document.createElement('div');
    блок.className = 'уведомление ' + (тип === 'успех' ? 'успех' : тип === 'ошибка' ? 'ошибка' : '');
    блок.textContent = (тип === 'успех' ? '✓ ' : тип === 'ошибка' ? '✕ ' : 'ℹ ') + текст;
    контейнер.appendChild(блок);
    
    // Автоматически удаляем через 3 секунды
    setTimeout(function() { блок.remove(); }, 3000);
}

// Функция вычисляет процент скидки
// Пример: цена=15000, стараяЦена=20000 → 25%
function процентСкидки(цена, стараяЦена) {
    if (!стараяЦена) return 0;  // если нет старой цены — скидки нет
    return Math.round((1 - цена / стараяЦена) * 100);
}


