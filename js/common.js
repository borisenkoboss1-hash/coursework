// ПОЧЕМУ УБРАЛИ ПОЛЯ "id" и "idПользователя"?
// - "id" записи не нужен, потому что вся корзина хранится в одном массиве
// - "idПользователя" не нужен, потому что ключ уже содержит идентификатор пользователя
