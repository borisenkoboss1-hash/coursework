// Функция возвращает объект с данными вошедшего пользователя
// Если пользователь не авторизован, возвращает null
function получитьПользователя() {
    // Читаем строку из localStorage
    const данные = localStorage.getItem('пользователь');
    
    // Если данных нет → 'null' → JSON.parse('null') → null
    // Если данные есть → '{"name":"Иван"}' → JSON.parse → {name:"Иван"}
    return JSON.parse(данные || 'null');
}


