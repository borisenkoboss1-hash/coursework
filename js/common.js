// ЧАСТЬ 2: РАБОТА С ID ПОЛЬЗОВАТЕЛЯ (ДЛЯ РАЗДЕЛЕНИЯ КОРЗИНЫ И ИЗБРАННОГО)
// ════════════════════════════════════════════════════════════════════════════════════════════════════════════
//
// ⚠️ ВАЖНО: Эта функция — КЛЮЧЕВОЕ ИСПРАВЛЕНИЕ!
// Раньше корзина и избранное были ОБЩИМИ для всех пользователей.
// Теперь каждый пользователь имеет СВОЮ корзину и СВОё избранное.
//
// КАК ЭТО РАБОТАЕТ:
// 1. Получаем данные текущего пользователя
// 2. Если пользователь не залогинен — возвращаем null (корзина не сохраняется)
// 3. Если залогинен — возвращаем уникальный идентификатор (телефон + email)
// 4. Этот идентификатор будет использоваться в КЛЮЧАХ localStorage
//
// ПРИМЕР: пользователь с телефоном "+79991234567" и email "ivan@mail.ru"
//          → ключ корзины: "корзина_+79991234567_ivan@mail.ru"
//          → ключ избранного: "избранное_+79991234567_ivan@mail.ru"
//
// ПОЧЕМУ ТЕЛЕФОН + EMAIL? Потому что телефон может повторяться (теоретически),
// а комбинация телефона и email — уникальна.
// ════════════════════════════════════════════════════════════════════════════════════════════════════════════

function получитьIdПользователяДляКлюча() {
    const пользователь = получитьПользователя();
    if (!пользователь) return null;  // не залогинен — возвращаем null
    
    // Используем телефон и email как уникальный идентификатор
    // Если одного из полей нет — используем то, что есть
    const телефон = пользователь.phone || '';
    const email = пользователь.email || '';
    const имя = пользователь.name || '';
    
    // Создаём уникальный ключ на основе доступных данных
    // Фильтруем пустые значения и объединяем через "_"
    const части = [телефон, email, имя].filter(ч => ч !== '');
    
    // Если нет никаких данных — используем fallback (но такого не должно быть)
    if (части.length === 0) return 'unknown_' + Date.now();
    
    return части.join('_');
}


