// localStorage — это память браузера. Данные сохраняются даже после перезагрузки страницы.

// ПОЛУЧЕНИЕ ДАННЫХ ИЗ localStorage:
// ------------------------------------------------------------
// получитьКорзину() — возвращает массив товаров в корзине
// Если в localStorage ничего нет, возвращает пустой массив []
function получитьКорзину() { 
    return JSON.parse(localStorage.getItem('корзина') || '[]'); 
}

// получитьИзбранное() — возвращает массив товаров в избранном
function получитьИзбранное() { 
    return JSON.parse(localStorage.getItem('избранное') || '[]'); 
}

// получитьПользователя() — возвращает объект с данными вошедшего пользователя
// Если никто не вошёл, возвращает null
function получитьПользователя() { 
    return JSON.parse(localStorage.getItem('пользователь') || 'null'); 
}

// ОБНОВЛЕНИЕ СЧЁТЧИКОВ (цифры у иконок корзины и избранного в шапке)
// ------------------------------------------------------------
function обновитьСчётчики() {
    var сК = document.getElementById('счетчик-корзины');
    var сИ = document.getElementById('счетчик-избранного');
    if (сК) сК.textContent = получитьКорзину().length;  // количество товаров в корзине
    if (сИ) сИ.textContent = получитьИзбранное().length; // количество товаров в избранном
}

// ПРОВЕРКА НАЛИЧИЯ ТОВАРА В КОРЗИНЕ/ИЗБРАННОМ
// ------------------------------------------------------------
function вКорзине(id) { 
    // .some() — возвращает true, если хотя бы один товар подходит под условие
    return получитьКорзину().some(function(т) { return т.idТовара === id; }); 
}

function вИзбранном(id) { 
    return получитьИзбранное().some(function(т) { return т.idТовара === id; }); 
}

// ДОБАВЛЕНИЕ ТОВАРА В КОРЗИНУ
// ------------------------------------------------------------
function добавитьВКорзину(id) {
    // 1. Проверяем, авторизован ли пользователь
    var польз = получитьПользователя();
    if (!польз) {
        уведомление('Войдите в аккаунт, чтобы добавить в корзину', 'ошибка');
        открытьМодалкуВхода();  // открываем окно входа
        return false;
    }
    
    // 2. Проверяем, не добавлен ли уже этот товар
    if (вКорзине(id)) { 
        уведомление('Товар уже в корзине'); 
        return false; 
    }
    
    // 3. Добавляем товар в массив корзины
    var корзина = получитьКорзину();
    корзина.push({ 
        id: Date.now(),                      // уникальный id записи (текущее время в миллисекундах)
        idПользователя: польз.id,           // id пользователя
        idТовара: id,                       // id товара
        количество: 1                       // начальное количество
    });
    
    // 4. Сохраняем обновлённую корзину в localStorage
    localStorage.setItem('корзина', JSON.stringify(корзина));
    
    // 5. Обновляем счётчик в шапке и показываем уведомление
    обновитьСчётчики();
    уведомление('Товар добавлен в корзину', 'успех');
    return true;
}

// УДАЛЕНИЕ ТОВАРА ИЗ КОРЗИНЫ
// ------------------------------------------------------------
function удалитьИзКорзины(id) {
    // .filter() — оставляет только те товары, у которых id НЕ РАВЕН удаляемому
    var корзина = получитьКорзину().filter(function(т) { return т.idТовара !== id; });
    localStorage.setItem('корзина', JSON.stringify(корзина));
    обновитьСчётчики();
    уведомление('Товар удалён из корзины');
}

// ДОБАВЛЕНИЕ/УДАЛЕНИЕ ТОВАРА В ИЗБРАННОЕ (функция-переключатель)
// ------------------------------------------------------------
function добавитьВИзбранное(id) {
    // 1. Проверяем авторизацию
    var польз = получитьПользователя();
    if (!польз) {
        уведомление('Войдите в аккаунт', 'ошибка');
        открытьМодалкуВхода();
        return false;
    }
    
    // 2. Если товар уже в избранном — удаляем его
    if (вИзбранном(id)) {
        var изб1 = получитьИзбранное().filter(function(т) { return т.idТовара !== id; });
        localStorage.setItem('избранное', JSON.stringify(изб1));
        обновитьСчётчики();
        уведомление('Удалено из избранного');
        return false;
    }
    
    // 3. Если товара нет — добавляем
    var изб2 = получитьИзбранное();
    изб2.push({ 
        id: Date.now(), 
        idПользователя: польз.id, 
        idТовара: id 
    });
    localStorage.setItem('избранное', JSON.stringify(изб2));
    обновитьСчётчики();
    уведомление('Добавлено в избранное ♡', 'успех');
    return true;
}


