// ПОЛУЧЕНИЕ КОРЗИНЫ ТЕКУЩЕГО ПОЛЬЗОВАТЕЛЯ
// Возвращает массив товаров в корзине
function получитьКорзину() {
    const userId = получитьIdПользователяДляКлюча();
    
    // Если пользователь не залогинен — возвращаем пустую корзину
    // (гость не может иметь корзину, так как мы не знаем, кто он)
    if (!userId) return [];
    
    // ✅ КЛЮЧ ЗАВИСИТ ОТ ПОЛЬЗОВАТЕЛЯ!
    const ключ = `корзина_${userId}`;
    const данные = localStorage.getItem(ключ);
    
    // Если данных нет — возвращаем пустой массив
    return данные ? JSON.parse(данные) : [];
}

// СОХРАНЕНИЕ КОРЗИНЫ ТЕКУЩЕГО ПОЛЬЗОВАТЕЛЯ
// (вспомогательная функция, не вызывается напрямую из других файлов)
function сохранитьКорзину(корзина) {
    const userId = получитьIdПользователяДляКлюча();
    if (!userId) return false;  // не залогинен — не можем сохранить
    
    const ключ = `корзина_${userId}`;
    localStorage.setItem(ключ, JSON.stringify(корзина));
    return true;
}

// ПРОВЕРКА НАЛИЧИЯ ТОВАРА В КОРЗИНЕ
function вКорзине(id) {
    // .some() — возвращает true, если хотя бы один товар подходит под условие
    return получитьКорзину().some(function(т) { return т.idТовара === id; });
}

// ДОБАВЛЕНИЕ ТОВАРА В КОРЗИНУ
function добавитьВКорзину(id) {
    // 1. Проверяем, авторизован ли пользователь
    var польз = получитьПользователя();
    if (!польз) {
        уведомление('Войдите в аккаунт, чтобы добавить в корзину', 'ошибка');
        открытьМодалкуВхода();  // открываем окно входа
        return false;
    }
    
    // 2. Проверяем, не добавлен ли уже этот товар
    if (вКорзине(id)) {
        уведомление('Товар уже в корзине');
        return false;
    }
    
    // 3. Добавляем товар в массив корзины
    var корзина = получитьКорзину();
    корзина.push({
        idТовара: id,           // id товара
        количество: 1          // начальное количество
    });
    
    // 4. Сохраняем обновлённую корзину (с привязкой к пользователю)
    сохранитьКорзину(корзина);
    
    // 5. Обновляем счётчик в шапке и показываем уведомление
    обновитьСчётчики();
    уведомление('Товар добавлен в корзину', 'успех');
    return true;
}

// УДАЛЕНИЕ ТОВАРА ИЗ КОРЗИНЫ
function удалитьИзКорзины(id) {
    // .filter() — оставляет только те товары, у которых id НЕ РАВЕН удаляемому
    var корзина = получитьКорзину().filter(function(т) { return т.idТовара !== id; });
    сохранитьКорзину(корзина);
    обновитьСчётчики();
    уведомление('Товар удалён из корзины');
}

// ИЗМЕНЕНИЕ КОЛИЧЕСТВА ТОВАРА В КОРЗИНЕ
function изменитьКоличество(id, дельта) {
    var корзина = получитьКорзину();
    var товар = корзина.find(function(т) { return т.idТовара === id; });
    
    if (товар) {
        var новоеКоличество = (товар.количество || 1) + дельта;
        // Ограничиваем от 1 до 99
        товар.количество = Math.max(1, Math.min(99, новоеКоличество));
        сохранитьКорзину(корзина);
        обновитьСчётчики();
    }
}

// УСТАНОВКА КОНКРЕТНОГО КОЛИЧЕСТВА ТОВАРА
function установитьКоличество(id, количество) {
    var корзина = получитьКорзину();
    var товар = корзина.find(function(т) { return т.idТовара === id; });
    
    if (товар) {
        товар.количество = Math.max(1, Math.min(99, количество));
        сохранитьКорзину(корзина);
        обновитьСчётчики();
    }
}


