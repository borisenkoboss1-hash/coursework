const API_URL = 'http://localhost:3005';

// ============================================================
// ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
// ============================================================

function getHeaders() {
    return {
        'Content-Type': 'application/json'
    };
}

function getCurrentUserId() {
    const user = получитьПользователя();
    return user ? user.id : null;
}

