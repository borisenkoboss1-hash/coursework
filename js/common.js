// ============================================================
// ПЕРЕКЛЮЧЕНИЕ ЯЗЫКА (РУССКИЙ/АНГЛИЙСКИЙ)
// ============================================================

// Текущий язык (читаем из localStorage или ставим русский по умолчанию)
// localStorage.getItem('язык') — читаем сохранённый язык из памяти браузера
// Если ничего не сохранено (null) — ставим 'ru' (русский)
// || — оператор "ИЛИ": если слева null/undefined, берётся значение справа
var текущийЯзык = localStorage.getItem('язык') || 'ru';


// ============================================================
// ФУНКЦИЯ НАСТРОЙКИ КНОПОК ПЕРЕКЛЮЧЕНИЯ ЯЗЫКА
// ============================================================
// Вызывается один раз при загрузке страницы
// Находит все кнопки с атрибутом data-lang и настраивает их поведение

function инициализироватьЯзык() {
    
    // document.querySelectorAll('[data-lang]') — находит ВСЕ элементы на странице,
    // у которых есть атрибут data-lang (например: <button data-lang="ru">)
    // .forEach() — для каждого найденного элемента выполняет функцию
    document.querySelectorAll('[data-lang]').forEach(function(кнопка) {
        
        // Читаем значение атрибута data-lang (например 'ru' или 'en')
        var яз = кнопка.getAttribute('data-lang');
        
        // Если атрибут пустой или не существует — пропускаем эту кнопку
        if (!яз) return;
        
        // ============================================================
        // ПОДСВЕЧИВАЕМ АКТИВНУЮ КНОПКУ
        // ============================================================
        // classList.toggle('active', условие) — добавляет класс 'active', если условие true,
        // и удаляет класс 'active', если условие false
        // Если язык кнопки совпадает с текущим языком → кнопка получает класс active
        // (становится оранжевой/жирной)
        кнопка.classList.toggle('active', яз === текущийЯзык);
        
        // ============================================================
        // НАВЕШИВАЕМ ОБРАБОТЧИК КЛИКА НА КНОПКУ
        // ============================================================
        кнопка.onclick = function() {
            
            // 1. Меняем переменную текущийЯзык на выбранный
            // Например, было 'ru', стало 'en'
            текущийЯзык = яз;
            
            // 2. Сохраняем выбор пользователя в localStorage
            // Ключ: 'язык', значение: 'ru' или 'en'
            // При следующей загрузке страницы выбор восстановится
            localStorage.setItem('язык', яз);
            
            // 3. Вызываем функцию, которая меняет текст на странице
            // Она пройдёт по всем элементам и заменит текст на выбранном языке
            применитьПеревод();
            
            // 4. Обновляем подсветку кнопок
            // Проходим по ВСЕМ кнопкам с data-lang и обновляем их класс active
            document.querySelectorAll('[data-lang]').forEach(function(к) {
                // Активной становится только та кнопка, чей язык совпадает с текущим
                к.classList.toggle('active', к.getAttribute('data-lang') === яз);
            });
        };
    });
    
    // Применяем перевод сразу после загрузки страницы (восстанавливаем сохранённый язык)
    применитьПеревод();
}


// ============================================================
// ФУНКЦИЯ ПРИМЕНЕНИЯ ПЕРЕВОДА
// ============================================================
// Заменяет текст на странице в соответствии с выбранным языком
// Вызывается при загрузке страницы и при клике на кнопку переключения языка

function применитьПеревод() {
    
    // переводы[текущийЯзык] — берём словарь для текущего языка
    // Например, если текущийЯзык = 'en', то пер = { 'Все двери': 'All doors', ... }
    var пер = переводы[текущийЯзык];
    
    // ============================================================
    // 1. ПЕРЕВОД ЭЛЕМЕНТОВ С АТРИБУТОМ data-i18n
    // ============================================================
    // Находим все элементы, у которых есть атрибут data-i18n
    // В HTML это выглядит так: <h1 data-i18n="Все двери">Все двери</h1>
    document.querySelectorAll('[data-i18n]').forEach(function(эл) {
        
        // Читаем значение атрибута data-i18n — это ключ для поиска перевода
        // Например: 'Все двери'
        var ключ = эл.getAttribute('data-i18n');
        
        // Если в словаре есть перевод для этого ключа
        if (пер[ключ]) {
            // Заменяем текст внутри элемента на перевод
            // Например, 'Все двери' → 'All doors'
            эл.textContent = пер[ключ];
        }
    });
    
    // ============================================================
    // 2. ПЕРЕВОД ССЫЛОК В МЕНЮ (у которых нет data-i18n)
    // ============================================================
    // Находим все ссылки в меню с классами .ссылка-меню и .моб-меню a
    document.querySelectorAll('.ссылка-меню, .моб-меню a').forEach(function(эл) {
        
        // Читаем сохранённый оригинальный текст из атрибута data-original
        var оригинал = эл.getAttribute('data-original');
        
        // Если атрибута data-original нет (первый раз переводим)
        if (!оригинал) {
            // Сохраняем текущий текст элемента в атрибут data-original
            // trim() — удаляем лишние пробелы в начале и конце
            эл.setAttribute('data-original', эл.textContent.trim());
            оригинал = эл.textContent.trim();
        }
        
        // Ищем перевод по сохранённому оригинальному тексту
        if (пер[оригинал]) {
            // Заменяем текст на перевод
            эл.textContent = пер[оригинал];
        }
    });
    
    // ============================================================
    // 3. ПЕРЕВОД ПЛЕЙСХОЛДЕРА В ПОЛЕ ПОИСКА
    // ============================================================
    // Находим поле поиска по классу .поле-поиска
    var поиск = document.querySelector('.поле-поиска');
    if (поиск) {
        // Меняем подсказку внутри поля ввода
        // пер['Поиск по каталогу...'] — берём перевод фразы
        // || 'Поиск...' — если перевода нет, оставляем 'Поиск...'
        поиск.placeholder = пер['Поиск по каталогу...'] || 'Поиск...';
        
        // Дополнительная функция для автоматического перевода остального текста
        автоматическийПеревод();
    }
    
    // ============================================================
    // 4. ПЕРЕВОД КНОПОК В ШАПКЕ (Войти, Избранное, Корзина)
    // ============================================================
    
    // Находим текст кнопки "Войти" в шапке
    // Селектор: элемент с id="ссылка-вход", внутри него элемент с классом .текст-иконки
    var входКнопка = document.querySelector('#ссылка-вход .текст-иконки');
    if (входКнопка && пер['Войти']) {
        входКнопка.textContent = пер['Войти'];   // 'Войти' → 'Sign in'
    }
    
    // Находим текст кнопки "Избранное" в шапке
    var избранноеКнопка = document.querySelector('a[href="favorites.html"] .текст-иконки');
    if (избранноеКнопка && пер['Избранное']) {
        избранноеКнопка.textContent = пер['Избранное'];   // 'Избранное' → 'Wishlist'
    }
    
    // Находим текст кнопки "Корзина" в шапке
    var корзинаКнопка = document.querySelector('a[href="cart.html"] .текст-иконки');
    if (корзинаКнопка && пер['Корзина']) {
        корзинаКнопка.textContent = пер['Корзина'];   // 'Корзина' → 'Cart'
    }
    
    // Выводим в консоль информацию о том, какой язык применён
    // Это помогает при отладке (можно увидеть, что перевод сработал)
    console.log('Перевод применён, язык:', текущийЯзык);
}
// ============================================================
// БУРГЕР-МЕНЮ (ДЛЯ МОБИЛЬНЫХ УСТРОЙСТВ)
// ============================================================
// Эта функция создаёт мобильное меню (бургер), которое:
// 1. Отображается только на маленьких экранах (CSS скрывает его на десктопе)
// 2. При клике на иконку бургера выезжает панель с навигацией
// 3. При клике на фон (оверлей) или на любую ссылку — меню закрывается

function инициализироватьБургер() {
    
    // ============================================================
    // ШАГ 1: НАХОДИМ ВСЕ НЕОБХОДИМЫЕ ЭЛЕМЕНТЫ НА СТРАНИЦЕ
    // ============================================================
    
    // Находим иконку бургера (три горизонтальные полоски)
    // В HTML это: <div class="бургер" id="бургер"><span></span><span></span><span></span></div>
    var бургер = document.getElementById('бургер');
    
    // Находим затемнённый фон (оверлей), который появляется поверх страницы при открытии меню
    // В HTML это: <div class="моб-оверлей" id="моб-оверлей"></div>
    var оверлей = document.getElementById('моб-оверлей');
    
    // Находим само мобильное меню (панель с ссылками)
    // В HTML это: <div class="моб-меню" id="моб-меню">...</div>
    var меню = document.getElementById('моб-меню');
    
    // Если хотя бы одного элемента нет на странице — выходим из функции
    // Например, на страницах, где не нужно мобильное меню
    if (!бургер || !меню || !оверлей) return;
    
    
    // ============================================================
    // ШАГ 2: НАСТРАИВАЕМ ОТКРЫТИЕ МЕНЮ ПРИ КЛИКЕ НА ИКОНКУ БУРГЕРА
    // ============================================================
    
    бургер.onclick = function() {
        // Показываем затемнённый фон (делаем его видимым)
        // style.display = 'block' — элемент появляется на странице
        // Фон занимает весь экран (position: fixed; inset: 0)
        оверлей.style.display = 'block';
        
        // Показываем панель меню
        меню.style.display = 'block';
        
        // requestAnimationFrame — просим браузер выполнить код перед следующей перерисовкой
        // Это нужно, чтобы анимация сработала правильно
        requestAnimationFrame(function() {
            // Добавляем класс 'открыто' к меню
            // В CSS этот класс сдвигает меню: right: 0 (выезжает на экран)
            меню.classList.add('открыто');
        });
    };
    
    
    // ============================================================
    // ШАГ 3: ФУНКЦИЯ ЗАКРЫТИЯ МЕНЮ
    // ============================================================
    // Создаём отдельную функцию, чтобы использовать её в нескольких местах
    // (при клике на фон, при клике на ссылки, при клике на крестик)
    
    function закрыть() {
        // Убираем класс 'открыто' — меню начинает уезжать вправо
        меню.classList.remove('открыто');
        
        // Ждём 300 миллисекунд (пока закончится анимация выезда)
        setTimeout(function() {
            // Скрываем затемнённый фон
            оверлей.style.display = 'none';
            // Скрываем панель меню
            меню.style.display = 'none';
        }, 300);  // 300ms — длительность анимации в CSS
    }
    
    
    // ============================================================
    // ШАГ 4: ПРИ КЛИКЕ НА ТЁМНЫЙ ФОН — ЗАКРЫВАЕМ МЕНЮ
    // ============================================================
    // Когда пользователь кликает на затемнённую область вне меню
    оверлей.onclick = закрыть;
    
    
    // ============================================================
    // ШАГ 5: ПРИ КЛИКЕ НА ЛЮБУЮ ССЫЛКУ В МЕНЮ — ЗАКРЫВАЕМ МЕНЮ
    // ============================================================
    // Находим ВСЕ ссылки внутри меню
    // menu.querySelectorAll('a') — ищем все теги <a> внутри элемента меню
    меню.querySelectorAll('a').forEach(function(а) {
        // На каждую ссылку вешаем обработчик клика
        // Когда пользователь кликает на ссылку — меню закрывается
        а.addEventListener('click', закрыть);
    });
}
