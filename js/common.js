// ============================================================
// Этот код автоматически добавляет в подвал (футер) сайта ссылки
// на специальные страницы для слабовидящих (accessible-*.html)

// DOMContentLoaded — событие, когда весь HTML страницы загружен
document.addEventListener('DOMContentLoaded', function() {
    
    // ============================================================
    // ШАГ 1: ПРОВЕРКА — НЕ НАХОДИМСЯ ЛИ УЖЕ НА СТРАНИЦЕ ДЛЯ СЛАБОВИДЯЩИХ?
    // ============================================================
    // window.location.pathname — путь текущей страницы (например: '/index.html')
    // .includes('accessible') — проверяет, есть ли слово 'accessible' в пути
    // Если мы уже на странице accessible.html — не добавляем ссылки (чтобы не было дублей)
    if (window.location.pathname.includes('accessible')) return;
    
    // ============================================================
    // ШАГ 2: НАХОДИМ ПОДВАЛ (ФУТЕР) НА СТРАНИЦЕ
    // ============================================================
    // .низ-подвала — это блок в самом низу страницы с дополнительными ссылками
    var низ = document.querySelector('.низ-подвала');
    
    // Если подвала нет на странице — выходим
    if (!низ) return;
    
    // Проверяем, нет ли уже ссылки на версию для слабовидящих
    // (чтобы не добавить второй раз)
    if (низ.querySelector('.ссылка-доступности-главная')) return;
    
    // ============================================================
    // ШАГ 3: СОЗДАЁМ БЛОК СО ССЫЛКАМИ
    // ============================================================
    
    // Создаём новый HTML-элемент <div>
    var блок = document.createElement('div');
    
    // Добавляем стили прямо в атрибут style
    // display: flex — располагаем ссылки в ряд
    // gap: 16px — расстояние между ссылками 16 пикселей
    // margin-top: 8px — отступ сверху 8 пикселей
    // flex-wrap: wrap — ссылки переносятся на новую строку, если не помещаются
    блок.style.cssText = 'display: flex; gap: 16px; margin-top: 8px; flex-wrap: wrap;';
    
    // Заполняем блок HTML-кодом со ссылками
    блок.innerHTML = `
        <a href="accessible.html" class="ссылка-доступности-главная" style="color:#888; font-size:12px; text-decoration:none;">👁 Версия для слабовидящих</a>
        <a href="accessible-catalog.html" style="color:#888; font-size:12px; text-decoration:none;">📋 Каталог</a>
        <a href="accessible-cart.html" style="color:#888; font-size:12px; text-decoration:none;">🛒 Корзина</a>
        <a href="accessible-delivery.html" style="color:#888; font-size:12px; text-decoration:none;">🚚 Доставка</a>
        <a href="accessible-about.html" style="color:#888; font-size:12px; text-decoration:none;">ℹ️ О нас</a>
    `;
    
    // ============================================================
    // ШАГ 4: ДОБАВЛЯЕМ ЭФФЕКТ ПРИ НАВЕДЕНИИ МЫШИ
    // ============================================================
    
    // Находим все ссылки внутри созданного блока
    блок.querySelectorAll('a').forEach(function(ссылка) {
        
        // При наведении мыши на ссылку — меняем цвет на оранжевый
        ссылка.addEventListener('mouseenter', function() { 
            ссылка.style.color = '#f26522';   // Оранжевый цвет
        });
        
        // Когда мышь уходит со ссылки — возвращаем серый цвет
        ссылка.addEventListener('mouseleave', function() { 
            ссылка.style.color = '#888';       // Серый цвет
        });
    });
    
    // ============================================================
    // ШАГ 5: ДОБАВЛЯЕМ БЛОК В ПОДВАЛ
    // ============================================================
    // Добавляем созданный блок в самый конец подвала
    низ.appendChild(блок);
});


