// ДОПОЛНИТЕЛЬНАЯ ФУНКЦИЯ: АВТОМАТИЧЕСКИЙ ПЕРЕВОД ВСЕГО ТЕКСТА
// ============================================================
// Эта функция пытается перевести любой текст на странице,
// даже если у элемента нет атрибута data-i18n
// Вызывается из функции применитьПеревод()

function автоматическийПеревод() {
    
    // Берём словарь для текущего языка (ru или en)
    var пер = переводы[текущийЯзык];
    
    // Находим все элементы, которые могут содержать текст
    // Перечисляем все теги, где обычно бывает текст
    var всеЭлементы = document.querySelectorAll('h1, h2, h3, h4, h5, h6, p, span, div, li, button, a, label, .ссылка-меню');
    
    // Перебираем каждый найденный элемент
    всеЭлементы.forEach(function(эл) {
        
        // ============================================================
        // ПРОПУСКАЕМ ЭЛЕМЕНТЫ, КОТОРЫЕ НЕ НУЖНО ПЕРЕВОДИТЬ
        // ============================================================
        
        // Если у элемента уже есть атрибут data-i18n — пропускаем
        // (такие элементы уже переведены в основной функции применитьПеревод)
        if (эл.hasAttribute('data-i18n')) return;
        
        // Получаем текст элемента и удаляем лишние пробелы
        var текст = эл.textContent.trim();
        
        // Если текст пустой или слишком короткий (меньше 2 символов) — пропускаем
        if (!текст || текст.length < 2) return;
        
        // Если текст содержит знак рубля (₽) или слово "руб" — это цена, пропускаем
        if (текст.includes('₽') || текст.includes('руб')) return;
        
        // Если текст начинается с цифры (/^\d/ — регулярное выражение для проверки)
        // Например: "15000 ₽" или "3 товара" — не переводим
        if (/^\d/.test(текст)) return;
        
        // ============================================================
        // ЕСЛИ ЕСТЬ ПЕРЕВОД — ЗАМЕНЯЕМ ТЕКСТ
        // ============================================================
        // проверяем, есть ли в словаре перевод для этого текста
        // И убеждаемся, что перевод не совпадает с оригиналом
        if (пер[текст] && пер[текст] !== текст) {
            // Заменяем текст элемента на перевод
            эл.textContent = пер[текст];
        }
    });
}


function очиститьLocalStorage() {
    // Список разрешённых ключей (то, что реально нужно для работы сайта)
    const разрешённыеКлючи = [
        'пользователь',   // данные вошедшего пользователя
        'тема',           // выбранная тема (light/dark)
        'язык',           // выбранный язык (ru/en)
        'а11й-размер',    // размер шрифта для слабовидящих
        'а11й-тема',      // цветовая тема для слабовидящих
        'а11й-интервал'   // межбуквенный интервал для слабовидящих
    ];
    
    // Перебираем все ключи в localStorage
    for (let i = 0; i < localStorage.length; i++) {
        const ключ = localStorage.key(i);
        
        // Проверяем, является ли ключ пользовательским (корзина_*, избранное_*)
        const являетсяПользовательскимКлючом = 
            ключ.startsWith('корзина_') || 
            ключ.startsWith('избранное_');
        
        // Если ключ НЕ в списке разрешённых И НЕ пользовательский — удаляем
        if (!разрешённыеКлючи.includes(ключ) && !являетсяПользовательскимКлючом) {
            localStorage.removeItem(ключ);
            console.log(`Очистка localStorage: удалён мусорный ключ "${ключ}"`);
        }
    }
}

