// ============================================================
// ИНИЦИАЛИЗАЦИЯ ВХОДА И ОБРАБОТКА ФОРМЫ
// ============================================================
// Эта функция:
// 1. Настраивает отображение кнопки входа в шапке (имя пользователя или "Войти")
// 2. Настраивает закрытие модалки по клику на фон и крестик
// 3. Обрабатывает отправку формы входа (проверка email/пароля)

function инициализироватьВход() {
    
    // ============================================================
    // ШАГ 1: НАСТРАИВАЕМ ОТОБРАЖЕНИЕ КНОПКИ ВХОДА В ШАПКЕ
    // ============================================================
    
    // Получаем данные текущего пользователя (если он авторизован)
    var польз = получитьПользователя();
    
    // Находим кнопку входа в шапке по ID
    var ссылка = document.getElementById('ссылка-вход');
    
    // СЛУЧАЙ 1: ПОЛЬЗОВАТЕЛЬ АВТОРИЗОВАН
    if (польз && ссылка) {
        // Меняем содержимое кнопки: иконка 👤 + имя пользователя
        // польз.name.split(' ')[0] — берём первую часть имени (до пробела)
        // Например: "Иван Петров" → "Иван"
        ссылка.innerHTML = '<span>👤</span><span class="текст-иконки">' + польз.name.split(' ')[0] + '</span>';
        
        // Меняем адрес, куда ведёт кнопка:
        // Если роль admin → ведёт на admin.html
        // Если роль user → ведёт на profile.html
        ссылка.href = польз.role === 'admin' ? 'admin.html' : 'profile.html';
    } 
    // СЛУЧАЙ 2: ПОЛЬЗОВАТЕЛЬ НЕ АВТОРИЗОВАН
    else if (ссылка) {
        // Кнопка никуда не ведёт (ссылка на текущую страницу)
        ссылка.href = '#';
        
        // При клике — открываем модальное окно входа
        ссылка.onclick = function(e) {
            e.preventDefault();        // Отменяем переход по ссылке (чтобы не прыгало вверх)
            открытьМодалкуВхода();     // Открываем модальное окно
        };
    }
    
    // ============================================================
    // ШАГ 2: НАСТРАИВАЕМ ЗАКРЫТИЕ МОДАЛКИ ПО КРЕСТИКУ
    // ============================================================
    
    // Находим кнопку закрытия (крестик) внутри модального окна
    var закрытьКн = document.getElementById('закрыть-модалку');
    if (закрытьКн) {
        // При клике на крестик — закрываем модалку
        закрытьКн.onclick = закрытьМодалкуВхода;
    }
    
    // ============================================================
    // ШАГ 3: НАСТРАИВАЕМ ЗАКРЫТИЕ МОДАЛКИ ПО КЛИКУ НА ФОН
    // ============================================================
    
    // Находим само модальное окно
    var модалка = document.getElementById('модалка-входа');
    if (модалка) {
        // Отслеживаем клик по всей модалке
        модалка.addEventListener('click', function(e) {
            // Если пользователь кликнул именно на ФОН модалки (а не на внутреннее содержимое)
            // e.target === модалка — проверяет, что клик был по самому элементу модалки
            if (e.target === модалка) {
                закрытьМодалкуВхода();   // Закрываем модалку
            }
        });
    }
    
    // ============================================================
    // ШАГ 4: ОБРАБОТКА ФОРМЫ ВХОДА (ОТПРАВКА ДАННЫХ)
    // ============================================================
    
    // Находим кнопку "Войти" внутри модального окна
    var кнВойти = document.getElementById('кнопка-входа');
    if (!кнВойти) return;   // Если кнопки нет — выходим
    
    // Обработчик клика по кнопке "Войти"
    кнВойти.onclick = async function() {
        
        // Находим поля формы: email и пароль
        var emailПоле = document.getElementById('email-входа');
        var парольПоле = document.getElementById('пароль-входа');
        if (!emailПоле || !парольПоле) return;
        
        // Читаем значения полей и удаляем лишние пробелы
        var email = emailПоле.value.trim();
        var пароль = парольПоле.value;
        
        // ============================================================
        // ВАЛИДАЦИЯ ПОЛЕЙ
        // ============================================================
        
        // Если email или пароль пустые
        if (!email || !пароль) {
            // Показываем красное уведомление
            уведомление('Заполните все поля', 'ошибка');
            return;   // Выходим, не отправляем запрос
        }
        
        // ============================================================
        // ЗАГРУЗКА ПОЛЬЗОВАТЕЛЕЙ И ПРОВЕРКА (через json-server)
        // ============================================================
        
        try {
            // Отправляем GET-запрос на json-server с фильтрами прямо в URL —
            // ?email=...&password=... возвращает только подходящих пользователей.
            // Это быстрее и безопаснее чем грузить ВСЕХ пользователей и искать на клиенте.
            var resp = await fetch(API_URL + '/users?email=' + encodeURIComponent(email) + '&password=' + encodeURIComponent(пароль));
            
            // Превращаем ответ в массив объектов пользователей (может быть 0 или 1)
            var список = await resp.json();
            
            // Если массив не пуст — пользователь найден
            var найден = список.length > 0 ? список[0] : null;
            
            // ============================================================
            // УСПЕШНЫЙ ВХОД
            // ============================================================
            
            if (найден) {
                // Сохраняем данные пользователя в localStorage
                // Превращаем объект в строку через JSON.stringify
                localStorage.setItem('пользователь', JSON.stringify(найден));
                
                // Показываем зелёное уведомление с приветствием
                уведомление('Добро пожаловать, ' + найден.name + '!', 'успех');
                
                // Закрываем модальное окно
                закрытьМодалкуВхода();
                
                // Перезагружаем страницу через 0.5 секунды
                // Это нужно, чтобы обновить интерфейс (показать имя пользователя в шапке)
                setTimeout(function() {
                    location.reload();   // Перезагрузка страницы
                }, 500);
            } 
            
            // ============================================================
            // НЕВЕРНЫЙ EMAIL ИЛИ ПАРОЛЬ
            // ============================================================
            
            else {
                // Показываем красное уведомление об ошибке
                уведомление('Неверный email или пароль', 'ошибка');
            }
        } 
        
        // ============================================================
        // ОШИБКА ЗАГРУЗКИ ФАЙЛА
        // ============================================================
        
        catch(err) {
            // Если файл users.json не найден или ошибка сети
            уведомление('Ошибка подключения. Запустите через Live Server.', 'ошибка');
        }
    };
}

// ============================================================
// ПРЕЛОАДЕР (АНИМАЦИЯ ЗАГРУЗКИ)
// ============================================================
// Прелоадер — это анимация (спиннер), которая показывается,
// пока страница полностью не загрузится.
// Эта функция скрывает прелоадер через небольшую задержку.

function скрытьПрелоадер() {
    
    // setTimeout — запускает функцию один раз через указанное время
    // Первый аргумент: функция, которую нужно выполнить
    // Второй аргумент: задержка в миллисекундах (400 мс = 0.4 секунды)
    setTimeout(function() {
        
        // Находим элемент прелоадера на странице по ID
        // В HTML это: <div id="прелоадер"><div class="спиннер"></div></div>
        var п = document.getElementById('прелоадер');
        
        // Если элемент существует на странице
        if (п) {
            // Добавляем класс 'hidden' к прелоадеру
            // В CSS этот класс делает элемент невидимым и отключает pointer-events
            // .hidden { opacity: 0; pointer-events: none; }
            п.classList.add('hidden');
        }
        
    }, 400);  // Задержка 400 миллисекунд
}


// ============================================================
// СБРОС НАСТРОЕК (тема, язык, доступность)
// ============================================================
// Эта функция позволяет пользователю сбросить все настройки интерфейса
// (тему, язык, режим доступности) до значений по умолчанию,
// сохраняя при этом важные данные (пользователя, корзину, избранное).

function инициализироватьСброс() {
    
    // ============================================================
    // ШАГ 1: НАХОДИМ КНОПКУ СБРОСА НА СТРАНИЦЕ
    // ============================================================
    
    // Находим кнопку сброса по ID
    // В HTML это: <button id="кнопка-сброса">Сбросить настройки</button>
    var кнопка = document.getElementById('кнопка-сброса');
    
    // Если кнопка не найдена на странице — выходим из функции
    // (на некоторых страницах кнопки может не быть)
    if (!кнопка) return;
    
    
    // ============================================================
    // ШАГ 2: НАСТРАИВАЕМ ПОВЕДЕНИЕ КНОПКИ ПРИ КЛИКЕ
    // ============================================================
    
    кнопка.onclick = function() {
        
        // ============================================================
        // ШАГ 3: ПОДТВЕРЖДЕНИЕ ДЕЙСТВИЯ
        // ============================================================
        // confirm() — показывает всплывающее окно с вопросом и кнопками "ОК" и "Отмена"
        // Возвращает true, если пользователь нажал "ОК", и false, если нажал "Отмена"
        if (confirm('Сбросить настройки (тема, язык, доступность)?')) {
            
            // ============================================================
            // ШАГ 4: СОХРАНЯЕМ ВАЖНЫЕ ДАННЫЕ ПЕРЕД ОЧИСТКОЙ
            // ============================================================
            // Сохраняем в переменные данные, которые НЕЛЬЗЯ удалять
            // (пользователь, корзина, избранное)
            
            // Данные авторизованного пользователя (сессия — остаётся)
            var польз = localStorage.getItem('пользователь');
            
            // Настройки интерфейса (тема и язык — остаются)
            var тема = localStorage.getItem('тема');
            var язык = localStorage.getItem('язык');

            // Примечание: корзина и избранное теперь хранятся НА СЕРВЕРЕ (json-server),
            // поэтому при очистке localStorage они не теряются — данные остаются в db.json
            
            // ============================================================
            // ШАГ 5: ОЧИЩАЕМ ВЕСЬ localStorage
            // ============================================================
            localStorage.clear();
            
            // ============================================================
            // ШАГ 6: ВОССТАНАВЛИВАЕМ ВАЖНЫЕ ДАННЫЕ
            // ============================================================
            // Возвращаем только сессию пользователя и настройки интерфейса
            if (польз) localStorage.setItem('пользователь', польз);
            if (тема)  localStorage.setItem('тема', тема);
            if (язык)  localStorage.setItem('язык', язык);
            
            
            // ============================================================
            // ШАГ 7: ПЕРЕЗАГРУЖАЕМ СТРАНИЦУ
            // ============================================================
            // location.reload() — перезагружает текущую страницу
            // После перезагрузки настройки (тема, язык) будут по умолчанию,
            // а пользователь останется авторизованным, корзина и избранное сохранятся
            location.reload();
        }
        // Если пользователь нажал "Отмена" — ничего не происходит
    };
}

