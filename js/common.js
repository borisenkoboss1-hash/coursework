// ОЧИСТКА localStorage ОТ МУСОРА
function очиститьLocalStorage() {
    const разрешённыеКлючи = [
        'пользователь',
        'корзина',
        'избранное',
        'тема',
        'язык',
        'а11й-размер',
        'а11й-тема',
        'а11й-интервал'
    ];
    
    // ⚠️ ВАЖНО: НЕ удаляем ключи с привязкой к пользователю!
    // Они имеют формат: "корзина_телефон_email" или "избранное_телефон_email"
    // Такие ключи нужно сохранить!
    
    for (let i = 0; i < localStorage.length; i++) {
        const ключ = localStorage.key(i);
        
        // Проверяем, является ли ключ пользовательским (корзина_*, избранное_*)
        const являетсяПользовательскимКлючом = 
            ключ.startsWith('корзина_') || 
            ключ.startsWith('избранное_');
        
        // Если ключ НЕ в списке разрешённых И НЕ пользовательский — удаляем
        if (!разрешённыеКлючи.includes(ключ) && !являетсяПользовательскимКлючом) {
            localStorage.removeItem(ключ);
            console.log(`Очистка localStorage: удалён мусорный ключ "${ключ}"`);
        }
    }
}

