// ============================================================
// ВСПЛЫВАЮЩЕЕ ОКНО КОРЗИНЫ (ПРИ НАВЕДЕНИИ НА ИКОНКУ)
// ============================================================
// Это попап (tooltip), который появляется при наведении мыши на иконку корзины
// Показывает мини-список товаров (до 4 штук) и итоговую сумму
// Пользователь может быстро увидеть, что в корзине, не переходя на страницу корзины

async function инициализироватьПопапКорзины() {
    
    // ============================================================
    // ШАГ 1: НАХОДИМ ИКОНКУ КОРЗИНЫ В ШАПКЕ САЙТА
    // ============================================================
    // Ищем элемент <a> с href="cart.html" и классом "иконка-ссылка"
    // Это иконка корзины в шапке, куда пользователь может кликнуть
    const иконкаКорзины = document.querySelector('a[href="cart.html"].иконка-ссылка');
    
    // Если иконка корзины не найдена на странице — выходим
    // (на страницах без шапки или с другой вёрсткой)
    if (!иконкаКорзины) return;
    
    
    // ============================================================
    // ШАГ 2: СОЗДАЁМ ВСПЛЫВАЮЩЕЕ ОКНО (ПОПАП)
    // ============================================================
    
    // Делаем родительский элемент (контейнер иконки) позиционированным
    // position: 'relative' нужно, чтобы попап позиционировался относительно него
    иконкаКорзины.parentElement.style.position = 'relative';
    
    // Создаём новый HTML-элемент <div> для попапа
    // Он пока пустой, его содержимое будет заполнено позже
    const popup = document.createElement('div');
    
    // Добавляем CSS-класс 'popup' для стилизации (фон, тень, скругление)
    popup.className = 'popup';
    
    // Добавляем ID для возможного использования в CSS или JS
    popup.id = 'popup-корзины';
    
    // Добавляем созданный попап как дочерний элемент к родителю иконки корзины
    // Теперь попап физически существует на странице, но скрыт (opacity: 0)
    иконкаКорзины.parentElement.appendChild(popup);
    
    
    // ============================================================
    // ШАГ 3: НАСТРАИВАЕМ ПОКАЗ ПОПАПА ПРИ НАВЕДЕНИИ
    // ============================================================
    
    // Когда мышь НАВОДИТСЯ на иконку корзины
    иконкаКорзины.addEventListener('mouseenter', () => показатьПопапКорзины(popup));
    
    // Когда мышь НАВОДИТСЯ на сам попап (чтобы он не исчезал, пока мышь на нём)
    popup.addEventListener('mouseenter', () => popup.classList.add('active'));
    
    // Когда мышь УХОДИТ с попапа
    popup.addEventListener('mouseleave', () => popup.classList.remove('active'));
    
    // Когда мышь УХОДИТ с иконки корзины
    иконкаКорзины.addEventListener('mouseleave', () => {
        // Ждём 100 миллисекунд (небольшая задержка для комфорта пользователя)
        setTimeout(() => {
            // Если мышь НЕ НАХОДИТСЯ на попапе (hover)
            if (!popup.matches(':hover')) {
                // Убираем класс active — попап исчезает
                popup.classList.remove('active');
            }
        }, 100);
    });
}


// ============================================================
// ФУНКЦИЯ ПОКАЗА ПОПАПА КОРЗИНЫ (ЗАПОЛНЕНИЕ СОДЕРЖИМЫМ)
// ============================================================
// Эта функция вызывается, когда пользователь наводит мышь на иконку корзины
// Она загружает актуальные данные о корзине и заполняет попап

async function показатьПопапКорзины(popup) {
    
    // ============================================================
    // ШАГ 1: ПОКАЗЫВАЕМ ПОПАП
    // ============================================================
    // Добавляем класс 'active' — попап становится видимым (opacity: 1)
    popup.classList.add('active');
    
    // ============================================================
    // ШАГ 2: ПОЛУЧАЕМ ТЕКУЩУЮ КОРЗИНУ ИЗ localStorage
    // ============================================================
    // получитьКорзину() — возвращает массив товаров в корзине
    const корзина = await получитьКорзину();
    
    
    // ============================================================
    // ШАГ 3: СЛУЧАЙ — КОРЗИНА ПУСТАЯ
    // ============================================================
    if (корзина.length === 0) {
        // Показываем сообщение о пустой корзине и ссылку на каталог
        popup.innerHTML = `
            <div class="popup-пусто">🛒 Корзина пуста</div>
            <a href="catalog.html" class="popup-кнопка">Перейти в каталог</a>
        `;
        return;   // Выходим, дальше не идём
    }
    
    
    // ============================================================
    // ШАГ 4: КОРЗИНА НЕ ПУСТА — ЗАГРУЖАЕМ ДАННЫЕ ТОВАРОВ
    // ============================================================
    
    try {
        // Загружаем товары с json-server (вместо статичного файла)
        // await — ждём ответа от сервера
        const resp = await fetch(API_URL + '/products');
        
        // Превращаем ответ в массив объектов товаров
        const товары = await resp.json();
        
        // Берём только ПЕРВЫЕ 4 товара из корзины (чтобы попап не был слишком большим)
        // .slice(0, 4) — создаёт новый массив с элементами 0, 1, 2, 3
        const элементы = корзина.slice(0, 4);
        
        // Переменная для подсчёта итоговой суммы (будет накапливаться)
        let итого = 0;
        
        // ============================================================
        // ШАГ 5: ФОРМИРУЕМ HTML-СТРОКИ ДЛЯ КАЖДОГО ТОВАРА
        // ============================================================
        // .map() — преобразует каждый товар из корзины в HTML-строку
        // .join('') — склеивает все строки в одну (убирает запятые)
        const строки = элементы.map(з => {
            
            // Находим полную информацию о товаре по его id
            // .find() — ищет товар, у которого id совпадает с idТовара из корзины
            const т = товары.find(т => т.id === з.idТовара);
            
            // Если товар не найден (маловероятно, но на всякий случай) — пропускаем
            if (!т) return '';
            
            // Вычисляем сумму по этому товару: цена × количество
            const сумма = т.price * (з.количество || 1);
            
            // Добавляем к общей сумме
            итого += сумма;
            
            // Возвращаем HTML-строку для одного товара в попапе
            return `
                <div class="popup-строка">
                    <span class="popup-назв">${т.name}</span>
                    <span class="popup-цена">${форматЦены(т.price)}</span>
                </div>
            `;
        }).join('');
        
        // ============================================================
        // ШАГ 6: ЕСЛИ ТОВАРОВ БОЛЬШЕ 4 — ПОКАЗЫВАЕМ СООБЩЕНИЕ "И ЕЩЁ X ТОВАРОВ"
        // ============================================================
        const доп = корзина.length > 4 
            ? `<div style="font-size:11px;color:var(--текст-светлый);text-align:center;padding:4px 0;">
                ...и ещё ${корзина.length - 4} товар(а)
               </div>` 
            : '';
        
        // ============================================================
        // ШАГ 7: СОБИРАЕМ ВЕСЬ ПОПАП
        // ============================================================
        popup.innerHTML = 
            строки +                          // Строки товаров
            доп +                             // Сообщение о дополнительных товарах
            `<div class="popup-итого">         // Блок итого
                <span>Итого:</span>
                <span>${форматЦены(итого)}</span>
             </div>` +
            `<a href="cart.html" class="popup-кнопка">Оформить заказ →</a>`;  // Кнопка перехода
        
    } catch (ошибка) {
        // Если произошла ошибка (например, файл products.json не загрузился)
        // Показываем упрощённый попап с одной кнопкой
        popup.innerHTML = '<a href="cart.html" class="popup-кнопка">Открыть корзину →</a>';
    }
}

