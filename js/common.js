async function обновитьСчётчики() {
    const корзина = await получитьКорзину();
    const избранное = await получитьИзбранное();
    
    const сК = document.getElementById('счетчик-корзины');
    const сИ = document.getElementById('счетчик-избранного');
    
    const общееКоличество = корзина.reduce((сумма, item) => сумма + (item.количество || 1), 0);
    
    if (сК) сК.textContent = общееКоличество;
    if (сИ) сИ.textContent = избранное.length;
    
    console.log('Счётчики обновлены. Корзина:', корзина);
}
