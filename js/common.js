// КНОПКА "НАВЕРХ" (ПРОКРУТКА К НАЧАЛУ СТРАНИЦЫ)
// ============================================================
// Эта функция создаёт кнопку, которая:
// 1. Появляется, когда пользователь прокрутил страницу вниз
// 2. При клике плавно возвращает его наверх страницы

