// ЧАСТЬ 5: ТАБЛИЦА ТОВАРОВ (отображение и управление)
// ════════════════════════════════════════════════════════════════════════════════════════════════════════════

// Функция получает массив товаров и рисует их в таблице на странице
// Параметр "товары" — это массив объектов, каждый объект описывает одну дверь (id, name, price и т.д.)
function заполнитьТаблицуТоваров(товары) {
    
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // ШАГ 1: СОЗДАЁМ ПЕРЕВОД НАЗВАНИЙ КАТЕГОРИЙ С АНГЛИЙСКОГО НА РУССКИЙ
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // В файле products.json категории хранятся на английском: entrance, interior, hardware
    // На странице мы хотим показывать по-русски: Входные, Межкомнатные, Фурнитура
    // const — создаём постоянный объект-словарь, который нельзя изменить
    const названияКат = { 
        entrance: 'Входные',      // если в данных ключ "entrance", покажем "Входные"
        interior: 'Межкомнатные', // если в данных ключ "interior", покажем "Межкомнатные"
        hardware: 'Фурнитура'     // если в данных ключ "hardware", покажем "Фурнитура"
    };
    
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // ШАГ 2: РИСУЕМ ТАБЛИЦУ, ПРЕВРАЩАЯ КАЖДЫЙ ТОВАР В СТРОКУ HTML
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // document.getElementById('тело-таблицы-товаров') — находим место в HTML, куда будем вставлять строки
    // .innerHTML = ... — заменяем содержимое этого места на новый HTML-код
    // товары.map(...) — берём каждый товар по очереди и превращаем в HTML-строку
    // .join('') — склеиваем все строки в одну (убираем запятые, которые добавляет .map)
    document.getElementById('тело-таблицы-товаров').innerHTML =
        товары.map(т => {
            // Переменная "т" — это один товар (одна дверь)
            // Например: { id: 1, name: "Дуб премиум", brand: "Бастион", price: 15000, article: "B-001", ... }
            
            // Возвращаем HTML-код для одной строки таблицы
            // Обратные кавычки `` позволяют вставлять переменные через ${}
            return `
                <tr>   <!-- tr = table row = строка таблицы -->
                    
                    <!-- ЯЧЕЙКА 1: ID товара (уникальный номер) -->
                    <!-- td = table data = ячейка таблицы -->
                    <!-- style="..." — меняем цвет и размер шрифта -->
                    <td style="color:var(--текст-светлый);font-size:11px;">${т.id}</td>
                    
                    <!-- ЯЧЕЙКА 2: НАЗВАНИЕ И АРТИКУЛ ТОВАРА -->
                    <td>
                        <div style="font-weight:600;font-size:13px;">${т.name}</div>      <!-- название жирным -->
                        <div style="font-size:11px;color:var(--текст-светлый);">${т.article}</div> <!-- артикул мелким -->
                    </td>
                    
                    <!-- ЯЧЕЙКА 3: КАТЕГОРИЯ (переводим с английского на русский) -->
                    <!-- названияКат[т.category] — берём перевод для категории товара -->
                    <!-- || т.category — если перевода нет (например, другая категория), показываем как есть -->
                    <td>${названияКат[т.category] || т.category}</td>
                    
                    <!-- ЯЧЕЙКА 4: БРЕНД (производитель) -->
                    <td>${т.brand}</td>
                    
                    <!-- ЯЧЕЙКА 5: ЦЕНА (форматируем с пробелами и значком ₽) -->
                    <!-- форматЦены(15000) вернёт "15 000 ₽" -->
                    <td style="font-weight:700;">${форматЦены(т.price)}</td>
                    
                    <!-- ЯЧЕЙКА 6: НАЛИЧИЕ (зелёный бейджик "Есть" или красный "Нет") -->
                    <td>
                        <!-- бейдж — это маленькая цветная метка -->
                        <!-- класс меняется в зависимости от наличия: бейдж-есть или бейдж-нет -->
                        <span class="бейдж ${т.inStock ? 'бейдж-есть' : 'бейдж-нет'}">
                            ${т.inStock ? 'Есть' : 'Нет'}   <!-- если inStock = true → "Есть", иначе "Нет" -->
                        </span>
                    </td>
                    
                    <!-- ЯЧЕЙКА 7: КНОПКИ ДЕЙСТВИЙ (Изменить и Удалить) -->
                    <td>
                        <div class="адм-действия">
                            <!-- Кнопка "Изменить" — атрибут data-ред хранит id товара -->
                            <!-- data-ред — это пользовательский атрибут, в нём можно хранить данные -->
                            <button class="адм-кн адм-кн-ред" data-ред="${т.id}">✏ Изменить</button>
                            <!-- Кнопка "Удалить" — атрибут data-удал хранит id товара -->
                            <button class="адм-кн адм-кн-удал" data-удал="${т.id}">✕</button>
                        </div>
                    </td>
                </tr>
            `;
        }).join('');  // join('') — склеиваем все строки таблицы в одну (без запятых)
    
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // ШАГ 3: НАВЕШИВАЕМ ОБРАБОТЧИКИ НА КНОПКИ (чтобы они что-то делали при нажатии)
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // Почему обработчики здесь, а не в HTML? Потому что кнопки создаются динамически,
    // и мы должны добавить им функционал ПОСЛЕ того, как они появились на странице
    
    // НАХОДИМ ВСЕ КНОПКИ "ИЗМЕНИТЬ" (все элементы с атрибутом data-ред)
    // document.querySelectorAll('[data-ред]') — ищет все элементы у которых есть атрибут data-ред
    // .forEach — для каждого найденного элемента выполняем функцию
    document.querySelectorAll('[data-ред]').forEach(кн => {
        // На каждую кнопку вешаем обработчик клика
        кн.addEventListener('click', () => {
            // кн.getAttribute('data-ред') — читаем значение атрибута (например "5")
            // + в начале превращает строку "5" в число 5
            const idТовара = +кн.getAttribute('data-ред');
            // открываем модальное окно для редактирования этого товара
            открытьМодалкуТовара(idТовара);
        });
    });
    
    // НАХОДИМ ВСЕ КНОПКИ "УДАЛИТЬ" (все элементы с атрибутом data-удал)
    document.querySelectorAll('[data-удал]').forEach(кн => {
        // async — функция-обработчик асинхронная, делает запрос к серверу
        кн.addEventListener('click', async () => {
            // confirm — показывает всплывающее окно с вопросом "Вы уверены?"
            // Пользователь может нажать "ОК" (true) или "Отмена" (false)
            if (confirm('Удалить товар?')) {
                
                // Берём id товара из атрибута и превращаем в число
                const id = +кн.getAttribute('data-удал');
                
                try {
                    // DELETE-запрос — удаляет товар с этим id на сервере
                    const ответ = await fetch(API_URL + '/products/' + id, {
                        method: 'DELETE'
                    });

                    if (!ответ.ok) throw new Error('Ошибка сервера при удалении');

                    // УДАЛЯЕМ ТОВАР ИЗ ЛОКАЛЬНОГО МАССИВА (чтобы таблица обновилась без перезагрузки)
                    // .filter() — создаёт НОВЫЙ массив, в который попадают только элементы,
                    // для которых функция вернула true
                    // т.id !== id — оставляем только те товары, у которых id НЕ РАВЕН удаляемому
                    всеТовары = всеТовары.filter(т => т.id !== id);
                    
                    // Перерисовываем таблицу с обновлённым массивом
                    заполнитьТаблицуТоваров(всеТовары);
                    
                    // Обновляем цифры на главной странице (количество товаров, диаграмму)
                  обновитьДашборд();
                    
                    // Показываем всплывающее сообщение об успехе
                    // "успех" — второй параметр означает тип сообщения (зелёное)
                    уведомление('Товар удалён', 'успех');

                } catch (e) {
                    уведомление('Не удалось удалить товар. Проверьте подключение к серверу.', 'ошибка');
                    console.error('Ошибка удаления товара:', e);
                }
            }
        });
    });
}


