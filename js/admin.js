// Эта функция настраивает поля поиска и фильтрации
// Вызывается один раз при загрузке страницы
function инициализироватьФильтрТоваров() {
    
    // НАХОДИМ ЭЛЕМЕНТЫ НА СТРАНИЦЕ
    const поиск = document.getElementById('поиск-товаров');     // поле ввода текста (input)
    const фильтр = document.getElementById('фильтр-категории'); // выпадающий список (select)
    
    // ВНУТРЕННЯЯ ФУНКЦИЯ, КОТОРАЯ ПРИМЕНЯЕТ ФИЛЬТРЫ
    // Она вызывается каждый раз, когда пользователь что-то меняет (печатает или выбирает категорию)
    function применить() {
        
        // ПОЛУЧАЕМ ЗНАЧЕНИЯ ИЗ ПОЛЕЙ
        const запрос = поиск.value.toLowerCase();   // текст поиска (переводим в нижний регистр)
        // Зачем toLowerCase()? Чтобы "Дуб" и "дуб" совпадали
        const кат = фильтр.value;                   // выбранная категория (entrance, interior, hardware или пустая строка)
        
        // ФИЛЬТРУЕМ ТОВАРЫ
        // .filter() — оставляет только те товары, которые подходят под условия
        const отфильтрованные = всеТовары.filter(т => {
            
            // ──────────────────────────────────────────────────────────────────────────────────────────────
            // УСЛОВИЕ 1: ПОИСК ПО НАЗВАНИЮ ИЛИ БРЕНДУ
            // ──────────────────────────────────────────────────────────────────────────────────────────────
            // .includes(запрос) — проверяет, содержит ли строка искомый текст
            // .toLowerCase() — приводим название и бренд тоже к нижнему регистру
            const поНазванию = т.name.toLowerCase().includes(запрос) || 
                               т.brand.toLowerCase().includes(запрос);
            // Если запрос = "дуб", то проверим:
            // - название "Дуб премиум" → "дуб премиум".includes("дуб") → true
            // - бренд "Бастион" → "бастион".includes("дуб") → false
            // поНазванию = true || false = true → товар подходит по поиску
            
            // ──────────────────────────────────────────────────────────────────────────────────────────────
            // УСЛОВИЕ 2: ФИЛЬТР ПО КАТЕГОРИИ
            // ──────────────────────────────────────────────────────────────────────────────────────────────
            // !кат — если категория НЕ ВЫБРАНА (пустая строка), то условие считается истинным
            // т.category === кат — если категория выбрана, проверяем совпадение
            const поКатегории = !кат || т.category === кат;
            // Если кат = "entrance" (выбрана категория "Входные двери"), то:
            // - товар с category = "entrance" → true
            // - товар с category = "interior" → false
            // Если кат = "" (пусто, категория не выбрана), то !кат = true → все товары подходят
            
            // Возвращаем true только если ОБА условия выполнены (&& — логическое И)
            return поНазванию && поКатегории;
        });
        
        // ПЕРЕРИСОВЫВАЕМ ТАБЛИЦУ С ОТФИЛЬТРОВАННЫМИ ТОВАРАМИ
        заполнитьТаблицуТоваров(отфильтрованные);
    }
    
    // НАВЕШИВАЕМ ОБРАБОТЧИКИ
    // 'input' — событие срабатывает при КАЖДОМ вводе символа в поле поиска
    поиск.addEventListener('input', применить);
    // 'change' — событие срабатывает при изменении выбранного значения в списке
    фильтр.addEventListener('change', применить);
}


