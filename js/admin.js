/*

1. ЧТО ТАКОЕ localStorage?
   -----------------------
   Это как блокнот, который браузер хранит на вашем компьютере.
   Данные не удаляются даже после перезагрузки или закрытия браузера.
   
   Команды:
   - localStorage.setItem('ключ', 'значение') — сохранить
   - localStorage.getItem('ключ') — прочитать
   - localStorage.removeItem('ключ') — удалить
   
   Пример:
   localStorage.setItem('имя', 'Иван');
   const имя = localStorage.getItem('имя');  // 'Иван'


2. ЧТО ТАКОЕ FETCH?
   -----------------
   Это команда "скачай файл". Работает как ссылка в браузере.
   
   Пример:
   const ответ = await fetch('data/products.json');
   const товары = await ответ.json();
   
   Первый await — ждём, пока файл скачается
   Второй await — ждём, пока файл превратится в массив/объект


3. ЧТО ТАКОЕ ASYNC/AWAIT?
   ------------------------
   async — ставится перед функцией, которая может ждать
   await — говорит "жди, пока выполнится команда"
   
   Без async/await код выполнится быстрее, чем загрузится файл, и будет ошибка


4. ЧТО ТАКОЕ МАССИВ (.forEach, .map, .filter, .find)?
   -----------------------------------------------------
   Массив — это список элементов с номерами (индексами), начиная с 0
   
   .forEach(элемент => { ... }) — выполняет код для каждого элемента
   .map(элемент => { ... }) — преобразует массив в новый массив
   .filter(элемент => условие) — оставляет только те элементы, где условие true
   .find(элемент => условие) — находит первый элемент, подходящий под условие


5. ЧТО ТАКОЕ ОБЪЕКТ?
   -----------------
   Объект — это структура с ключами и значениями (как ящик с ячейками)
   
   Пример:
   const дверь = {
       id: 1,          // ключ "id" = значение 1
       имя: "Дуб",     // ключ "имя" = значение "Дуб"
       цена: 15000     // ключ "цена" = значение 15000
   };
   
   Доступ к значению:
   дверь.имя   // "Дуб"
   дверь.цена  // 15000


6. ЧТО ТАКОЕ ПЕРЕМЕННЫЕ (let, const)?
   ----------------------------------
   let — можно менять значение (переменная)
   const — нельзя менять значение (константа)
   
   let счётчик = 0;
   счётчик = 5;  // можно
   
   const имя = "Иван";
   имя = "Петр";  // ошибка!


7. КАК РАБОТАЕТ ТЕРНАРНЫЙ ОПЕРАТОР (? :)?
   ---------------------------------------
   Это "если-иначе" в одну строку
   
   условие ? значениеЕслиИстина : значениеЕслиЛожь
   
   Пример:
   const статус = товар.вНаличии ? "Есть" : "Нет";
   // если товар есть, то статус = "Есть", иначе "Нет"

*/


