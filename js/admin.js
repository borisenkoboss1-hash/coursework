// Эта функция настраивает ВСЕ кнопки, связанные с модальным окном товара
// Вызывается ОДИН раз при загрузке страницы
// Модальное окно — это всплывающее окно, которое появляется поверх страницы
function инициализироватьМодалкуТовара() {
    
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // 1. КНОПКА "ДОБАВИТЬ ТОВАР" (вверху таблицы, оранжевая)
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // Находим кнопку с id="добавить-товар"
    // addEventListener('click', ...) — ждём, когда пользователь нажмёт на кнопку
    // () => открытьМодалкуТовара(null) — стрелочная функция, которая вызовет открытие модалки
    // null передаётся, потому что это НОВЫЙ товар (нет id для редактирования)
    document.getElementById('добавить-товар').addEventListener('click', () => открытьМодалкуТовара(null));
    
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // 2. КНОПКА "СОХРАНИТЬ" (внутри модального окна, оранжевая)
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // Когда пользователь заполнил форму и нажал "Сохранить"
    // вызывается функция сохранитьТовар() (она создаёт или обновляет товар)
    document.getElementById('сохранить-товар').addEventListener('click', сохранитьТовар);
    
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // 3. КНОПКА "ЗАКРЫТЬ" (крестик ✕ в правом верхнем углу модалки)
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    document.getElementById('закрыть-товар-модалку').addEventListener('click', () => {
        // Находим модальное окно и удаляем класс active (оно становится невидимым)
        document.getElementById('модалка-товара').classList.remove('active');
        // Возвращаем возможность прокручивать страницу (до этого мы её отключили)
        // overflow: hidden → overflow: '' (значение по умолчанию, прокрутка работает)
        document.body.style.overflow = '';
    });
    
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // 4. КЛИК ПО ФОНУ (серой затемнённой области ЗА модальным окном)
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // Это хороший UX (пользовательский опыт): если кликнуть вне окна, оно закроется
    // e — это событие (объект с информацией о клике)
    document.getElementById('модалка-товара').addEventListener('click', e => {
        // e.target — элемент, на котором произошёл клик (куда именно нажали)
        // Если кликнули ИМЕННО по фону модалки (а не по внутреннему белому окну)
        // То есть: e.target === сама модалка (серый фон), а не что-то внутри неё
        if (e.target === document.getElementById('модалка-товара')) {
            // Закрываем модалку
            document.getElementById('модалка-товара').classList.remove('active');
            // Возвращаем прокрутку
            document.body.style.overflow = '';
        }
    });
}


