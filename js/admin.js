// Эта функция обновляет все цифры и графики на главной странице админки
async function обновитьДашборд() {
    
    // ───────────────────────────────────────────────────────────────────────
    // 4.1. КАРТОЧКИ СО СТАТИСТИКОЙ (4 прямоугольника вверху)
    // ───────────────────────────────────────────────────────────────────────
    
    // document — это вся веб-страница
    // .getElementById('стат-товаров') — находим элемент с таким ID на странице
    // .textContent — текст внутри этого элемента
    // = — присваиваем новое значение
    // всеТовары.length — сколько товаров в массиве (например, 15)
    
    // Пример: находим на странице место с id="стат-товаров"
    // и пишем туда число: "15"
    document.getElementById('стат-товаров').textContent = всеТовары.length;
    
    // То же самое для пользователей
    document.getElementById('стат-польз').textContent = всеПользователи.length;
    
    // получитьКорзину() — функция из common.js
    // возвращает массив товаров, которые лежат в корзинах покупателей
    const корзина = await получитьКорзину();
    
    // Показываем количество товаров в корзинах
    document.getElementById('стат-корзины').textContent = корзина.length;
    
    // ───────────────────────────────────────────────────────────────────────
    // 4.2. ПОТЕНЦИАЛЬНАЯ ВЫРУЧКА (сумма денег во всех корзинах)
    // ───────────────────────────────────────────────────────────────────────
    
    // let — создаём переменную, которую будем менять
    // выручка — начинаем с нуля
    let выручка = 0;
    
    // .forEach() — перебирает каждый элемент массива по очереди
    // з — это один элемент из корзины (одна запись о товаре)
    корзина.forEach(з => {
        // .find() — ищет товар в массиве всеТовары по id
        // т.id === з.idТовара — сравниваем id товара из корзины с id в общем списке
        const т = всеТовары.find(т => т.id === з.idТовара);
        
        // if (т) — "если товар найден" (не пустой)
        if (т) {
            // добавляем к выручке: цена × количество
            // || 1 — если количество не указано, считаем что 1
            выручка = выручка + (т.price * (з.количество || 1));
            // сокращённая запись: выручка += т.price * (з.количество || 1)
        }
    });
    
    // форматЦены() — функция из common.js
    // превращает число 15000 в строку "15 000 ₽"
    document.getElementById('стат-выручка').textContent = форматЦены(выручка);
    
    // ───────────────────────────────────────────────────────────────────────
    // 4.3. ДИАГРАММА КАТЕГОРИЙ (полоски: сколько товаров в каждой категории)
    // ───────────────────────────────────────────────────────────────────────
    
    // СОЗДАЁМ СЧЁТЧИК КАТЕГОРИЙ
    // { } — фигурные скобки создают объект (как ящик с ячейками)
    // entrance: 0 — ячейка с названием "entrance" и значением 0
    const кат = { 
        entrance: 0,   // входные двери (пока 0)
        interior: 0,   // межкомнатные двери (пока 0)
        hardware: 0    // фурнитура (пока 0)
    };
    
    // ПЕРЕБИРАЕМ ВСЕ ТОВАРЫ И ЗАПОЛНЯЕМ СЧЁТЧИК
    // всеТовары.forEach(т => ...) — для каждого товара выполняем код
    всеТовары.forEach(т => {
        // т.category — категория текущего товара (например, 'entrance')
        // кат[т.category] — заглядываем в ящик с таким названием
        // !== undefined — проверяем, существует ли такая категория
        if (кат[т.category] !== undefined) {
            // увеличиваем значение в этой категории на 1
            кат[т.category] = кат[т.category] + 1;
            // сокращённая запись: кат[т.category]++;
        }
    });
    
    // НАХОДИМ МАКСИМАЛЬНОЕ КОЛИЧЕСТВО (для масштабирования полосок)
    // Object.values(кат) — достаёт все значения из объекта (например [5, 8, 3])
    // ... — "оператор spread", распаковывает массив в отдельные числа
    // Math.max(5, 8, 3) — находит самое большое число (вернёт 8)
    const максимум = Math.max(...Object.values(кат));
    
    // РУССКИЕ НАЗВАНИЯ КАТЕГОРИЙ (для отображения на экране)
    const названия = { 
        entrance: 'Входные двери', 
        interior: 'Межкомнатные двери', 
        hardware: 'Фурнитура' 
    };
    
    // РИСУЕМ ПОЛОСКИ ДИАГРАММЫ
    // Object.entries(кат) — превращает объект в массив:
    // [['entrance', 5], ['interior', 8], ['hardware', 3]]
    
    // .map() — преобразует массив в HTML-строки
    // .join('') — склеивает все строки в одну
    document.getElementById('диаграмма-категорий').innerHTML =
        Object.entries(кат).map(([к, кол]) => {
            // вычисляем ширину полоски в процентах
            // если максимум есть, делим количество на максимум и умножаем на 100
            // например: 8 / 8 * 100 = 100% (самая длинная полоска)
            const ширина = максимум ? (кол / максимум) * 100 : 0;
            
            // возвращаем HTML-код одной полоски
            return `
            <div class="кат-строка">
                <div class="кат-лейбл">
                    <span>${названия[к]}</span>   <!-- "Входные двери" -->
                    <span>${кол} шт.</span>        <!-- "5 шт." -->
                </div>
                <div class="кат-полоска">
                    <div class="кат-заполнение" style="width:${ширина}%"></div>
                </div>
            </div>
        `;
        }).join('');
    
    // ───────────────────────────────────────────────────────────────────────
    // 4.4. ПОСЛЕДНИЕ 5 ПОЛЬЗОВАТЕЛЕЙ (кто недавно зарегистрировался)
    // ───────────────────────────────────────────────────────────────────────
    
    // ШАГ 1: СОРТИРУЕМ ПОЛЬЗОВАТЕЛЕЙ ПО ДАТЕ РЕГИСТРАЦИИ
    // [...всеПользователи] — создаём КОПИЮ массива (чтобы не испортить оригинал)
    // .sort() — сортирует массив
    // (a, b) => new Date(b.createdAt) - new Date(a.createdAt) — сортировка от новых к старым
    // new Date() — превращает строку с датой в специальный объект, который можно сравнивать
    
    const последние = [...всеПользователи]
        .sort((a, b) => {
            // превращаем даты в числа (миллисекунды)
            const датаA = new Date(a.createdAt);
            const датаB = new Date(b.createdAt);
            // если датаB больше датаA, то b встанет раньше a
            return датаB - датаA;
        })
        .slice(0, 5);  // .slice(0,5) — берём первые 5 элементов из отсортированного массива
    
    // ШАГ 2: РИСУЕМ СПИСОК ПОСЛЕДНИХ ПОЛЬЗОВАТЕЛЕЙ
    // .map() — превращает каждого пользователя в HTML-строку
    document.getElementById('посл-пользователи').innerHTML =
        последние.map(п => {
            // п.name[0] — первая буква имени (для аватара)
            const перваяБуква = п.name[0];
            
            // определяем класс бейджика (админ или обычный)
            const классБейджа = п.role === 'admin' ? 'бейдж-админ' : 'бейдж-польз';
            
            // возвращаем HTML-код одного пользователя
            return `
            <div style="display:flex;align-items:center;gap:10px;padding:6px 0;border-bottom:1px solid var(--рамка);">
                <!-- Круглый аватар с первой буквой имени -->
                <div style="width:32px;height:32px;border-radius:50%;background:var(--оранжевый);display:flex;align-items:center;justify-content:center;color:white;font-weight:700;font-size:13px;flex-shrink:0;">
                    ${перваяБуква}
                </div>
                <!-- Имя и email -->
                <div style="flex:1;min-width:0;">
                    <div style="font-size:13px;font-weight:600;overflow:hidden;text-overflow:ellipsis;white-space:nowrap;">${п.name}</div>
                    <div style="font-size:11px;color:var(--текст-светлый);">${п.email}</div>
                </div>
                <!-- Бейджик роли -->
                <span class="бейдж ${классБейджа}">${п.role}</span>
            </div>
        `;
        }).join('');
}


