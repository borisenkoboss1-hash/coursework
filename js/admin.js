// Эта функция настраивает:
// 1. Отображение имени администратора в шапке
// 2. Кнопку "Выйти" (очищает данные и перенаправляет на страницу входа)
function инициализироватьВыход() {
    
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // 1. ПОКАЗЫВАЕМ ИМЯ АДМИНИСТРАТОРА В ШАПКЕ
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // Находим элемент с id="адм-имя" (например, <span id="адм-имя"></span>)
    const имяЭл = document.getElementById('адм-имя');
    
    // Проверяем: элемент существует И пользователь (админ) существует
    // && — логическое И (оба условия должны быть истинны)
    if (имяЭл && польз) {
        // Вставляем имя пользователя внутрь элемента
        // Например: польз.name = "Иван Петров" → в шапке появится "Иван Петров"
        имяЭл.textContent = польз.name;
    }
    
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // 2. КНОПКА "ВЫЙТИ"
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // Находим кнопку выхода (обычно в правом верхнем углу)
    document.getElementById('адм-выход').addEventListener('click', () => {
        
        // УДАЛЯЕМ ДАННЫЕ О ПОЛЬЗОВАТЕЛЕ ИЗ ПАМЯТИ
        // localStorage — это хранилище браузера (данные не удаляются при перезагрузке)
        // 'пользователь' — ключ, по которому мы сохраняли данные о вошедшем
        // removeItem — удаляет этот ключ и его значение
        localStorage.removeItem('пользователь');
        
        // ПЕРЕНАПРАВЛЯЕМ НА СТРАНИЦУ ВХОДА
        // window.location.href — меняет адрес в браузере (как если бы пользователь перешёл по ссылке)
        window.location.href = 'login.html';
        
        // После этого пользователь должен снова ввести логин и пароль
        // Чтобы зайти в админку, ему нужно будет снова пройти проверку (const польз = получитьПользователя())
    });
}


