/*

1. ЧТО ТАКОЕ МОДАЛЬНОЕ ОКНО?
   -------------------------
   Модальное окно — это всплывающее окно, которое блокирует взаимодействие с основной страницей.
   Обычно используется для форм (добавить/редактировать товар).
   В коде: .модалка — затемнённый фон, .модалка-внутри — белое окно с формой.
   Класс .active делает окно видимым (в CSS: display: flex вместо display: none).

2. ЧТО ТАКОЕ localStorage?
   ------------------------
   Это хранилище браузера. Данные НЕ УДАЛЯЮТСЯ при перезагрузке страницы или закрытии браузера.
   - localStorage.setItem('ключ', 'значение') — сохранить
   - localStorage.getItem('ключ') — прочитать
   - localStorage.removeItem('ключ') — удалить
   В админке мы храним: 'пользователь' — данные о вошедшем админе.

3. ЧТО ТАКОЕ event (e) В ОБРАБОТЧИКЕ КЛИКА?
   -----------------------------------------
   Когда пользователь кликает, браузер создаёт объект события (event).
   У этого объекта есть свойства:
   - e.target — на каком элементе произошёл клик (куда именно нажали)
   - e.preventDefault() — отменить стандартное действие (например, отправку формы)
   В коде: e.target === document.getElementById('модалка-товара') — проверяем,
   кликнули ли по самому фону модалки, а не по внутреннему окну.

4. ПОЧЕМУ МЫ ПЕРЕДАЁМ null В открытьМодалкуТовара?
   -------------------------------------------------
   Функция открытьМодалкуТовара(id) принимает id товара.
   - Если id = число (например 5) → открывается окно РЕДАКТИРОВАНИЯ товара с id=5
   - Если id = null → открывается окно ДОБАВЛЕНИЯ НОВОГО товара (все поля пустые)
   Это единая функция для двух режимов.

5. ПОЧЕМУ МЫ ВЫКЛЮЧАЕМ ПРОКРУТКУ (overflow: hidden)?
   --------------------------------------------------
   Когда модальное окно открыто, мы не хотим, чтобы пользователь скроллил фон.
   Это улучшает UX: всё внимание на форме.
   После закрытия возвращаем прокрутку (overflow: '').

6. ПОЧЕМУ ВЫЗОВ ФУНКЦИЙ В DOMContentLoaded?
   -----------------------------------------
   Скрипты могут выполняться ДО того, как браузер создаст HTML-элементы.
   Если мы попытаемся найти элемент по id, которого ещё нет, получим null и ошибку.
   DOMContentLoaded гарантирует: HTML загружен, элементы существуют.

7. ПОРЯДОК ВЫЗОВА ФУНКЦИЙ ВАЖЕН?
   ------------------------------
   Нет, функции инициализации (инициализироватьНавигацию, инициализироватьМодалкуТовара и т.д.)
   просто навешивают обработчики. Они не зависят друг от друга.
   А вот загрузитьДанные() может быть вызвана в любом месте после DOMContentLoaded.

8. ЧТО ДЕЛАЕТ загрузитьДанные()?
   ------------------------------
   - Загружает файлы products.json и users.json
   - Сохраняет их в переменные всеТовары и всеПользователи
   - Вызывает функции для отображения данных на странице
   Если файлы не найдены или ошибка — показывает уведомление

*/

