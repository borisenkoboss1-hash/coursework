    // 2. НАСТРАИВАЕМ КНОПКИ МОДАЛЬНОГО ОКНА ТОВАРА
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // Функция инициализироватьМодалкуТовара() описана выше
    // Она настраивает кнопки "Добавить товар", "Сохранить", "Закрыть" и клик по фону
    инициализироватьМодалкуТовара();
    
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // 3. НАСТРАИВАЕМ ПОИСК И ФИЛЬТР ТОВАРОВ
    // ──────────────────────────────────────────────────────────────────────────────────────────────────────
    // Функция инициализироватьФильтрТоваров() описана выше
    // Она настраивает поле поиска (по названию/бренду) и выпадающий список категорий
    инициализироватьФильтрТоваров();
    
