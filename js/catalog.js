// async — функция асинхронная (ждёт загрузки файла)
async function загрузитьТовары() {
    try {
        // fetch — браузер идёт на сервер и просит файл data/products.json
        // await — ждём ответа (может быть 0.1–2 секунды)
        const resp = await fetch(API_URL + '/products');
        
        // .json() — превращаем JSON-текст в массив JavaScript-объектов
        всеТовары = await resp.json();
        
        // ═══════════════════════════════════════════════════════════════════════
        // КАК РАБОТАЕТ ЧТЕНИЕ ПАРАМЕТРОВ ИЗ URL?
        // ═══════════════════════════════════════════════════════════════════════
        // Пример: пользователь перешёл по ссылке catalog.html?cat=entrance&search=дверь
        // 1. применитьФильтрыИзURL() читает window.location.search (часть после ?)
        // 2. new URLSearchParams() разбирает строку в объект
        // 3. params.get('cat') вернёт 'entrance'
        // 4. params.get('search') вернёт 'дверь'
        // 5. Устанавливаем фильтры.категория = 'entrance' и фильтры.поиск = 'дверь'
        // 6. Заполняем поле поиска на странице
        применитьФильтрыИзURL();
        
        // Заполняем фильтры (подкатегории, цвета) на основе загруженных товаров
        заполнитьФильтры();
        
        // Обновляем каталог (применяем фильтры, сортировку, рисуем карточки, пагинацию)
        обновитьКаталог();
        
    } catch (e) {
        // Если ошибка (файл не найден или запущено не через Live Server)
        console.error('Ошибка загрузки товаров:', e);
        document.getElementById('сетка-товаров').innerHTML =
            '<div style="padding:40px;text-align:center;">Ошибка загрузки товаров. Запустите через локальный сервер.</div>';
    }
}

// Читаем параметры из URL: catalog.html?cat=entrance&search=дверь
function применитьФильтрыИзURL() {
    // window.location.search — строка после ? (например: "?cat=entrance&search=дверь")
    // new URLSearchParams() — встроенный класс для разбора параметров
    const params = new URLSearchParams(window.location.search);
    
    // ──────────────────────────────────────────────────────────────────────────
    // Чтение категории из URL
    // ──────────────────────────────────────────────────────────────────────────
    const кат = params.get('cat');  // например "entrance"
    if (кат) фильтры.категория = кат;  // устанавливаем фильтр категории

    // ──────────────────────────────────────────────────────────────────────────
    // Чтение поискового запроса из URL (пришёл с главной страницы или с поиска)
    // ──────────────────────────────────────────────────────────────────────────
    // Поддержка поиска из главной страницы: catalog.html?search=...
    const запросURL = params.get('search');
    if (запросURL) {
        фильтры.поиск = запросURL;  // сохраняем поисковый запрос в фильтры
        
        // Находим поле поиска на странице и вставляем туда текст
        const поле = document.getElementById('поле-поиска');
        if (поле) поле.value = запросURL;  // чтобы пользователь видел, что ищем
    }

    // ──────────────────────────────────────────────────────────────────────────
    // Обновляем заголовок страницы и хлебные крошки (навигацию)
    // ──────────────────────────────────────────────────────────────────────────
    // Объект-словарь: ключ (значение из URL) → русское название
    const названия = { 
        entrance: 'Входные двери', 
        interior: 'Межкомнатные двери', 
        hardware: 'Фурнитура', 
        all: 'Все двери' 
    };
    const заголовок = названия[кат] || 'Все двери';
    
    // Меняем текст в заголовке H1
    document.getElementById('заголовок-каталога').textContent = заголовок;
    // Меняем текст в хлебной крошке (навигационной цепочке)
    document.getElementById('крошка-категория').textContent = заголовок;

    // ──────────────────────────────────────────────────────────────────────────
    // Подсвечиваем активный пункт меню (шапка сайта)
    // ──────────────────────────────────────────────────────────────────────────
    // Находим все пункты меню с классом .ссылка-меню
    document.querySelectorAll('.ссылка-меню').forEach(ссылка => {
        // Проверяем, совпадает ли data-cat у ссылки с выбранной категорией
        const активна = ссылка.getAttribute('data-cat') === кат;
        // Добавляем/удаляем класс active
        ссылка.classList.toggle('active', активна);
    });
}


