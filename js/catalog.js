// ════════════════════════════════════════════════════════════════════════════════════════════════════════════
// ЧАСТЬ 4: ПРИМЕНЕНИЕ ФИЛЬТРОВ И СОРТИРОВКИ
// ════════════════════════════════════════════════════════════════════════════════════════════════════════════
//
// КАК РАБОТАЕТ ФИЛЬТРАЦИЯ:
// 1. Функция применитьФильтры() проходит по ВСЕМ товарам
// 2. Для каждого товара проверяет ВСЕ активные фильтры
// 3. Если товар проходит все проверки — остаётся в отфильтрованные
// 4. Если нет — исключается
//

function применитьФильтры() {
    // .filter() — создаёт новый массив, в который попадают только товары,
    // для которых функция-проверка вернула true
    отфильтрованные = всеТовары.filter(т => {
        
        // ──────────────────────────────────────────────────────────────────────
        // ФИЛЬТР 1: ПО КАТЕГОРИИ
        // ──────────────────────────────────────────────────────────────────────
        // Если категория не 'all' И категория товара не совпадает — исключаем
        if (фильтры.категория !== 'all' && т.category !== фильтры.категория) return false;
        
        // ──────────────────────────────────────────────────────────────────────
        // ФИЛЬТР 2: ПО ПОДКАТЕГОРИИ
        // ──────────────────────────────────────────────────────────────────────
        // Если выбрана подкатегория И подкатегория товара не совпадает — исключаем
        if (фильтры.подкатегория && т.subcategory !== фильтры.подкатегория) return false;
        
        // ──────────────────────────────────────────────────────────────────────
        // ФИЛЬТР 3: ПО ЦЕНЕ
        // ──────────────────────────────────────────────────────────────────────
        // Проверяем: цена товара должна быть в диапазоне [ценаОт, ценаДо]
        if (т.price < фильтры.ценаОт || т.price > фильтры.ценаДо) return false;
        
        // ──────────────────────────────────────────────────────────────────────
        // ФИЛЬТР 4: ПО ЦВЕТУ
        // ──────────────────────────────────────────────────────────────────────
        if (фильтры.цвета.length > 0) {
            // Карта групп цветов → список ключевых слов (названий цветов)
            const цветаКарта = {
                'Белый':   ['Белый', 'Белый матовый', 'Белый ясень', 'Белый дуб', 'Белый бетон', 'Белый шёлк', 'Слоновая кость', 'Дуб белый', 'Ясень белый', 'Белый RAL 9016'],
                'Чёрный':  ['Чёрный', 'Чёрный матовый', 'Чёрный бархат', 'Чёрный шёлк', 'Антрацит', 'Графит', 'Серый цемент'],
                'Серый':   ['Серый', 'Серый бетон', 'Серый дуб', 'Рустик серый', 'Серый RAL 7035', 'Никель матовый', 'Матовый никель'],
                'Венге':   ['Венге', 'Тёмный орех', 'Шоколад', 'Орех'],
                'Дуб':     ['Дуб', 'Дуб Royal', 'Дуб беленый', 'Дуб тёмный', 'Дуб скай', 'Дуб молочный', 'Натуральный дуб', 'Тик', 'Ясень натуральный', 'Ясень светлый', 'Cappuccino', 'Рустик беж'],
                'Металл':  ['Хром', 'Серебро', 'Никель', 'Нержавеющая сталь', 'Сатин', 'Антик серебро', 'Антик медь', 'Бронза', 'Бронза антик', 'Золото', 'Золото антик'],
                'Коричн.': ['Коричневый', 'Rovere Scuro', 'Rovere Chiaro'],
            };
            
            // flatMap() — превращает массив групп в массив цветов
            // Например: ['Белый', 'Дуб'] → ['Белый','Белый матовый',...,'Дуб','Дуб Royal',...]
            const нужныеЦвета = фильтры.цвета.flatMap(г => цветаКарта[г] || []);
            
            // Получаем список цветов товара (из данных)
            const цветаТовара = т.colors || [];
            
            // .some() — проверяет, есть ли хотя бы одно совпадение
            // Сравниваем: есть ли среди нужных цветов такой, который есть в товаре
            if (!нужныеЦвета.some(ц => цветаТовара.some(тц => тц.includes(ц) || ц.includes(тц)))) return false;
        }
        
        // ──────────────────────────────────────────────────────────────────────
        // ФИЛЬТР 5: ПО ПОИСКУ (текст из поля)
        // ──────────────────────────────────────────────────────────────────────
        if (фильтры.поиск) {
            const запрос = фильтры.поиск.toLowerCase();  // приводим к нижнему регистру
            // Проверяем, содержится ли запрос в названии ИЛИ в бренде
            if (!т.name.toLowerCase().includes(запрос) &&
                !т.brand.toLowerCase().includes(запрос)) return false;
        }
        
        // Если все проверки пройдены — товар остаётся
        return true;
    });
}

// Сортировка отфильтрованных товаров по выбранному критерию
function применитьСортировку() {
    // Получаем выбранное значение из выпадающего списка
    const значение = document.getElementById('сортировка').value;
    
    // Создаём копию массива (чтобы не мутировать оригинал)
    const copy = [...отфильтрованные];
    
    // ──────────────────────────────────────────────────────────────────────────
    // КАК РАБОТАЕТ .sort()
    // sort() получает функцию сравнения (a, b)
    // - Если вернуть отрицательное число → a идёт раньше b
    // - Если вернуть 0 → порядок не меняется
    // - Если вернуть положительное число → b идёт раньше a
    // ──────────────────────────────────────────────────────────────────────────
    
    if (значение === 'price-asc')  // По возрастанию цены (дешёвые сверху)
        copy.sort((a, b) => a.price - b.price);
    
    if (значение === 'price-desc') // По убыванию цены (дорогие сверху)
        copy.sort((a, b) => b.price - a.price);
    
    if (значение === 'rating')     // По рейтингу (лучшие сверху)
        copy.sort((a, b) => b.rating - a.rating);
    
    if (значение === 'name')       // По названию (алфавитный порядок)
        // localeCompare — сравнивает строки с учётом русского языка
        copy.sort((a, b) => a.name.localeCompare(b.name, 'ru'));
    
    отфильтрованные = copy;
}


