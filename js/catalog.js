// Сколько товаров показываем на одной странице (12 — хорошее число для сетки 3x4)
const ТОВАРОВ_НА_СТРАНИЦЕ = 12;

// Текущее состояние каталога — все эти переменные меняются при взаимодействии пользователя
let всеТовары = [];           // ВСЕ товары из products.json (загружаются один раз)
let отфильтрованные = [];     // Товары после применения фильтров (меняется при фильтрации)
let текущаяСтраница = 1;      // Какая страница сейчас открыта (1, 2, 3...)
let текущийВид = 'сетка';     // 'сетка' — карточки в 3 колонки, 'список' — в 1 колонку

// Активные фильтры — объект, в котором хранятся ВСЕ выбранные пользователем ограничения
// Как это работает: когда пользователь что-то выбирает, мы меняем этот объект,
// а потом пересчитываем отфильтрованные товары
let фильтры = {
    категория: 'all',         // 'all' / 'entrance' / 'interior' / 'hardware'
    подкатегория: null,       // например 'Межкомнатные' или 'Фурнитура для дверей'
    ценаОт: 0,                // минимальная цена (0 = без ограничения)
    ценаДо: 100000,           // максимальная цена (100000 = без ограничения)
    бренды: [],               // массив выбранных брендов (на этом сайте не используется)
    цвета: [],                // массив выбранных групп цветов: ['Белый', 'Дуб']
    поиск: ''                 // текст из поля поиска
};


