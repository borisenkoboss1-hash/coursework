// ЧАСТЬ 6: ПАГИНАЦИЯ (постраничная навигация)
// ════════════════════════════════════════════════════════════════════════════════════════════════════════════
//
// КАК РАБОТАЕТ ПАГИНАЦИЯ:
// 1. Считаем общее количество страниц: всего = round(отфильтрованные.length / 12)
// 2. Если товаров меньше 12 — пагинация не показывается
// 3. Показываем: «Назад», номера страниц (с умными троеточиями), «Вперёд»
// 4. При клике на номер страницы меняем текущаяСтраница и обновляем каталог
//

function нарисоватьПагинацию() {
    // Вычисляем общее количество страниц (округляем вверх)
    const всего = Math.ceil(отфильтрованные.length / ТОВАРОВ_НА_СТРАНИЦЕ);
    const контейнер = document.getElementById('пагинация');
    
    // Если всего 1 страница или меньше — пагинация не нужна
    if (всего <= 1) { 
        контейнер.innerHTML = ''; 
        return; 
    }

    let html = '';

    // ──────────────────────────────────────────────────────────────────────────
    // КНОПКА "НАЗАД" (стрелка влево)
    // ──────────────────────────────────────────────────────────────────────────
    // Если мы на первой странице — кнопка неактивна (disabled)
    html += `<button class="стр-кнопка" id="стр-назад" ${текущаяСтраница === 1 ? 'disabled' : ''}>‹</button>`;

    // ──────────────────────────────────────────────────────────────────────────
    // КНОПКИ СТРАНИЦ (с умными троеточиями)
    // ──────────────────────────────────────────────────────────────────────────
    // Логика: показываем первую, последнюю и страницы рядом с текущей
    // Остальные заменяем на "..."
    for (let i = 1; i <= всего; i++) {
        // Условия для показа страницы:
        // - Это первая страница
        // - ИЛИ это последняя страница
        // - ИЛИ расстояние от текущей страницы <= 2 (текущая-1, текущая, текущая+1, текущая+2)
        if (i === 1 || i === всего || Math.abs(i - текущаяСтраница) <= 2) {
            html += `<button class="стр-кнопка ${i === текущаяСтраница ? 'active' : ''}" data-стр="${i}">${i}</button>`;
        } 
        // Если расстояние ровно 3 — вставляем троеточие
        else if (Math.abs(i - текущаяСтраница) === 3) {
            html += `<span style="color:var(--текст-светлый)">…</span>`;
        }
    }

    // ──────────────────────────────────────────────────────────────────────────
    // КНОПКА "ВПЕРЁД" (стрелка вправо)
    // ──────────────────────────────────────────────────────────────────────────
    html += `<button class="стр-кнопка" id="стр-вперёд" ${текущаяСтраница === всего ? 'disabled' : ''}>›</button>`;

    контейнер.innerHTML = html;

    // ──────────────────────────────────────────────────────────────────────────
    // НАВЕШИВАЕМ ОБРАБОТЧИКИ НА КНОПКИ СТРАНИЦ
    // ──────────────────────────────────────────────────────────────────────────
    контейнер.querySelectorAll('[data-стр]').forEach(кнопка => {
        кнопка.addEventListener('click', () => {
            текущаяСтраница = +кнопка.getAttribute('data-стр');
            обновитьКаталог();                // обновляем товары
            window.scrollTo({ top: 0, behavior: 'smooth' });  // плавно скроллим наверх
        });
    });
    
    // Обработчики для стрелок
    const назад = document.getElementById('стр-назад');
    const вперёд = document.getElementById('стр-вперёд');
    
    if (назад) {
        назад.onclick = () => { 
            if (текущаяСтраница > 1) { 
                текущаяСтраница--; 
                обновитьКаталог(); 
                window.scrollTo({top: 0, behavior: 'smooth'});
            }
        };
    }
    
    if (вперёд) {
        вперёд.onclick = () => { 
            if (текущаяСтраница < всего) { 
                текущаяСтраница++; 
                обновитьКаталог(); 
                window.scrollTo({top: 0, behavior: 'smooth'});
            }
        };
    }
}


