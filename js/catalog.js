// 5. flatMap() — как map, но "разворачивает" массивы на один уровень
//    Пример: [['a','b'], ['c']].flatMap(x => x) → ['a','b','c']
//
// 6. some() — проверяет, есть ли хотя бы один элемент, подходящий условию
//    Пример: цвета.some(ц => ц === 'Белый') — true если есть белый
//
