    // 1. ЗАПОЛНЕНИЕ ПОДКАТЕГОРИЙ
    // ──────────────────────────────────────────────────────────────────────────
    // Собираем уникальные подкатегории из товаров, которые соответствуют выбранной категории
    // [...new Set(...)] — конструкция для получения уникальных значений
