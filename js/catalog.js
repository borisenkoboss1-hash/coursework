// ЧАСТЬ 7: ТЕГИ ВЫБРАННЫХ ЦВЕТОВ (над списком товаров)
// ════════════════════════════════════════════════════════════════════════════════════════════════════════════
//
// Когда пользователь выбирает цвета, над товарами появляются теги с названиями цветов
// При клике на тег — цвет удаляется из фильтра
//

function обновитьТегиЦветов() {
    const контейнер = document.getElementById('выбранные-цвета');
    if (!контейнер) return;
    
    // Если нет выбранных цветов — скрываем контейнер
    if (фильтры.цвета.length === 0) { 
        контейнер.innerHTML = ''; 
        return; 
    }
    
    // Создаём HTML-теги для каждого выбранного цвета
    контейнер.innerHTML = фильтры.цвета.map(ц => `
        <span class="тег-цвета" data-удалить-цвет="${ц}">
            ${ц} ✕  <!-- Крестик для удаления -->
        </span>
    `).join('');
    
    // При клике на крестик — удаляем цвет из фильтра
    контейнер.querySelectorAll('[data-удалить-цвет]').forEach(тег => {
        тег.addEventListener('click', () => {
            const ц = тег.getAttribute('data-удалить-цвет');
            фильтры.цвета = фильтры.цвета.filter(х => х !== ц);
            
            // Убираем активный класс с цветного кружочка
            const свотч = document.querySelector(`[data-цвет="${ц}"]`);
            if (свотч) свотч.classList.remove('active');
            
            обновитьТегиЦветов();   // обновляем теги (удаляем этот)
            текущаяСтраница = 1;    // возвращаемся на первую страницу
            обновитьКаталог();       // обновляем товары
        });
    });
}


